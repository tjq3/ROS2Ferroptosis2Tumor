function usePar = configureParallel(requested,autoStart,nWorkers,jobStorage,scriptDir)
    % Robust Windows parallel preflight.
    % MATLAB local process pools can fail with
    % "Invalid character code sequence detected" when the project,
    % JobStorageLocation, or related worker paths contain non-ASCII chars.
    % In that case we deliberately use the already-implemented serial loops.

    usePar = false;
    if ~requested
        fprintf('Parallel execution not requested; using serial loops.\n');
        return;
    end

    % Do NOT call parpool at all when the project/current folder is non-ASCII.
    % This is the important fix for the user's current Chinese project path.
    pathCandidates = {pwd, scriptDir};
    for kk = 1:numel(pathCandidates)
        pp = pathCandidates{kk};
        if containsNonASCII(pp)
            warning(['Parallel pool disabled because the project/current path ', ...
                'contains non-ASCII characters:\n  %s\n', ...
                'Using serial loops instead. This changes only runtime, not ', ...
                'the model or numerical results.\n', ...
                'To enable parfor, move the project to an ASCII-only folder ', ...
                'and use an ASCII-only JobStorageLocation.'],pp);
            return;
        end
    end

    try
        hasPCT = license('test','Distrib_Computing_Toolbox');
        if ~hasPCT
            warning('Parallel Computing Toolbox unavailable; using serial loops.');
            return;
        end

        % Reuse an existing pool when possible.
        pool = gcp('nocreate');
        if ~isempty(pool)
            usePar = true;
            fprintf('Reusing existing parallel pool with %d workers.\n',pool.NumWorkers);
            return;
        end

        if ~autoStart
            fprintf('No existing pool and AUTO_START_POOL=false; using serial loops.\n');
            return;
        end

        clusterObj = parcluster('local');

        % Optional explicit ASCII-only JobStorageLocation.
        if ~isempty(jobStorage)
            if containsNonASCII(jobStorage)
                warning(['Requested JobStorageLocation contains non-ASCII ', ...
                    'characters; using serial loops:\n  %s'],jobStorage);
                return;
            end
            if ~exist(jobStorage,'dir')
                [ok,msg] = mkdir(jobStorage);
                if ~ok
                    warning('Could not create JobStorageLocation (%s); using serial loops.',msg);
                    return;
                end
            end
            clusterObj.JobStorageLocation = jobStorage;
        else
            % The profile's default JobStorageLocation can itself contain a
            % non-ASCII Windows user name. Check it before parpool startup.
            try
                js = clusterObj.JobStorageLocation;
            catch
                js = '';
            end
            if ~isempty(js) && containsNonASCII(js)
                warning(['Parallel pool disabled because the local-profile ', ...
                    'JobStorageLocation contains non-ASCII characters:\n  %s\n', ...
                    'Using serial loops. Set PARALLEL_JOB_STORAGE to an ', ...
                    'ASCII-only folder after moving the project.'],js);
                return;
            end
        end

        fprintf('Starting local parallel pool with %d workers...\n',nWorkers);
        pool = parpool(clusterObj,nWorkers);
        usePar = ~isempty(pool);

    catch ME
        warning(['Parallel setup failed before simulation:\n  %s\n', ...
            'Falling back to serial loops. Model definition and random-seed ', ...
            'logic are unchanged.'],ME.message);
        usePar = false;
    end
end

function tf = containsNonASCII(s)
    if isempty(s)
        tf = false;
        return;
    end
    c = char(s);
    tf = any(double(c(:)) > 127);
end

function [IT_C,IT_G] = simulateTDInputBank(p,td,nCells,seed)
    rng(seed,'twister');

    nSteps = round(td.T_s/td.dt_s);
    recEvery = round(td.bin_s/td.dt_s);
    nBins = round(td.T_s/td.bin_s);

    x1_0 = binornd(p.N,p.p_x1_ss,nCells,1);
    c1_0 = gamrnd(p.shape1,p.theta1,nCells,1);
    c2_0 = gamrnd(p.shape2,p.theta2,nCells,1);

    % CIR and GammaOU begin from identical stationary molecular/rate states.
    x1C=x1_0; x2C=p.N-x1C; c1C=c1_0; c2C=c2_0;
    x1G=x1_0; x2G=p.N-x1G; c1G=c1_0; c2G=c2_0;

    binC=zeros(nCells,1);
    binG=zeros(nCells,1);
    IT_C=zeros(nCells,nBins);
    IT_G=zeros(nCells,nBins);

    ib=1;
    for it=1:nSteps
        % CIR strict TD-CME.
        c1old=c1C; c2old=c2C;
        c1C=cirExactTransition(c1C,p.kappa1,p.shape1,p.theta1,td.dt_s);
        c2C=cirExactTransition(c2C,p.kappa2,p.shape2,p.theta2,td.dt_s);

        H1=0.5*(c1old+c1C)*td.dt_s;
        H2=0.5*(c2old+c2C)*td.dt_s;
        pr1=min(max(1-exp(-H1),0),1);
        pr2=min(max(1-exp(-H2),0),1);

        r1=binornd(x1C,pr1);
        r2=binornd(x2C,pr2);
        x1C=x1C-r1+r2;
        x2C=p.N-x1C;
        binC=binC+r1;

        % GammaOU strict TD-CME.
        [c1G,H1g]=gammaOUStepWithIntegral(c1G,p.a1,p.kappa1,p.theta1,td.dt_s);
        [c2G,H2g]=gammaOUStepWithIntegral(c2G,p.a2,p.kappa2,p.theta2,td.dt_s);

        pr1g=min(max(1-exp(-H1g),0),1);
        pr2g=min(max(1-exp(-H2g),0),1);

        r1g=binornd(x1G,pr1g);
        r2g=binornd(x2G,pr2g);
        x1G=x1G-r1g+r2g;
        x2G=p.N-x1G;
        binG=binG+r1g;

        if mod(it,recEvery)==0
            % events/min on [t_n,t_{n+1})
            IT_C(:,ib)=binC/(td.bin_s/60);
            IT_G(:,ib)=binG/(td.bin_s/60);
            binC(:)=0;
            binG(:)=0;
            ib=ib+1;
        end
    end

    assert(ib==nBins+1,'TD recording-bin mismatch.');
end

function cNext = cirExactTransition(c,kappa,shape,theta,dt)
    if dt==0
        cNext=c;
        return;
    end
    e=exp(-kappa*dt);
    ome=1-e;
    scale=0.5*theta*ome;
    df=2*shape;
    nc=2*e*max(c,0)./(theta*ome);

    if exist('ncx2rnd','file')==2
        cNext=scale.*ncx2rnd(df,nc);
    else
        Kp=poissrnd(nc/2);
        cNext=scale.*gamrnd(df/2+Kp,2);
    end
    cNext=max(cNext,0);
end

function [cNew,I] = gammaOUStepWithIntegral(cOld,a,kappa,theta,dt)
    if dt==0
        cNew=cOld;
        I=zeros(size(cOld));
        return;
    end

    n=numel(cOld);
    decay=exp(-kappa*dt);
    cNew=cOld*decay;
    I=cOld*(1-decay)/kappa;

    Nj=poissrnd(a*dt,n,1);
    idx=find(Nj>0);
    for ii=1:numel(idx)
        j=idx(ii);
        m=Nj(j);
        U=dt*rand(m,1);
        Y=gamrnd(1,theta,m,1);
        cNew(j)=cNew(j)+sum(Y.*exp(-kappa*(dt-U)));
        I(j)=I(j)+sum(Y.*(1-exp(-kappa*(dt-U)))/kappa);
    end

    cNew=max(cNew,0);
    I=max(I,0);
end

function inputMat = simulateSpatialInputBankNSM(c1,c2,out,win, ...
        x1_0,x2_0,tEdges,nRep,seedBase,usePar)

    nBins=numel(tEdges)-1;
    inputMat=zeros(nRep,nBins);

    if usePar
        parfor r=1:nRep
            rng(seedBase+r,'twister');
            inputMat(r,:)=simulateSpatialInputOneNSM( ...
                c1,c2,out,win,x1_0,x2_0,tEdges);
        end
    else
        for r=1:nRep
            rng(seedBase+r,'twister');
            inputMat(r,:)=simulateSpatialInputOneNSM( ...
                c1,c2,out,win,x1_0,x2_0,tEdges);
            if mod(r,max(1,round(nRep/10)))==0
                fprintf('  finished %d / %d spatial trajectories\n',r,nRep);
            end
        end
    end
end

function IS = simulateSpatialInputOneNSM(c1,c2,out,win,x1_0,x2_0,tEdges)
    K=numel(c1);
    nBins=numel(tEdges)-1;
    dtBin=tEdges(2)-tEdges(1);

    x1=x1_0(:);
    x2=x2_0(:);

    voxelRate=x1.*(c1+out.q1sum)+x2.*(c2+out.q2sum);
    tree=fenwickBuild(voxelRate);

    % windowCounts(k) counts R1 events occurring in W_k during current bin.
    windowCounts=zeros(K,1);
    IS=zeros(1,nBins);

    t=tEdges(1);
    ib=1;
    Tend=tEdges(end);

    while t<Tend
        a0=fenwickTotal(tree);
        if ~(a0>0) || ~isfinite(a0)
            break;
        end

        tau=-log(rand)/a0;
        tNext=t+tau;

        % Finalize every bin boundary reached before the next reaction event.
        while ib<=nBins && tEdges(ib+1)<=min(tNext,Tend)+1e-14
            density=windowCounts./(win.size*dtBin);
            IS(ib)=sqrt(mean(density.^2));
            windowCounts(:)=0;
            ib=ib+1;
        end

        if tNext>Tend
            break;
        end

        k=fenwickFind(tree,rand*a0);

        aR1=c1(k)*x1(k);
        aR2=c2(k)*x2(k);
        aD1=out.q1sum(k)*x1(k);
        aD2=out.q2sum(k)*x2(k);
        aLocal=aR1+aR2+aD1+aD2;

        if aLocal<=0
            old=voxelRate(k);
            voxelRate(k)=0;
            tree=fenwickAdd(tree,k,-old);
            t=tNext;
            continue;
        end

        u=rand*aLocal;
        touched=k;

        if u<=aR1
            x1(k)=x1(k)-1;
            x2(k)=x2(k)+1;

            centers=win.centersByVoxel{k};
            if ~isempty(centers)
                windowCounts(centers)=windowCounts(centers)+1;
            end

        elseif u<=aR1+aR2
            x2(k)=x2(k)-1;
            x1(k)=x1(k)+1;

        elseif u<=aR1+aR2+aD1
            j=chooseDestination(out.to1{k},out.q1{k});
            x1(k)=x1(k)-1;
            x1(j)=x1(j)+1;
            touched=[k;j]; %#ok<AGROW>

        else
            j=chooseDestination(out.to2{k},out.q2{k});
            x2(k)=x2(k)-1;
            x2(j)=x2(j)+1;
            touched=[k;j]; %#ok<AGROW>
        end

        [voxelRate,tree]=refreshVoxelRates(unique(touched),voxelRate,tree, ...
            x1,x2,c1,c2,out.q1sum,out.q2sum);

        t=tNext;
    end

    % Fill remaining empty bins after process stops / reaches Tend.
    while ib<=nBins
        density=windowCounts./(win.size*dtBin);
        IS(ib)=sqrt(mean(density.^2));
        windowCounts(:)=0;
        ib=ib+1;
    end
end

function R = evaluateFateRoutes(IT,IS,meso,dt,Tobs)
    assert(isequal(size(IT),size(IS)),'T and S input matrices must match.');

    UT  = meso.omegaT*IT;
    US  = meso.omegaS*IS;
    UTS = UT+US;

    FPT_T  = propagateLPOExact(UT, meso.rhoL,meso.ML,meso.L0,dt,Tobs);
    FPT_S  = propagateLPOExact(US, meso.rhoL,meso.ML,meso.L0,dt,Tobs);
    FPT_TS = propagateLPOExact(UTS,meso.rhoL,meso.ML,meso.L0,dt,Tobs);

    crossT  = FPT_T<=Tobs;
    crossS  = FPT_S<=Tobs;
    crossTS = FPT_TS<=Tobs;

    routeCode=zeros(size(FPT_TS));

    % 1 T-sufficient
    routeCode(crossT & ~crossS)=1;

    % 2 S-sufficient
    routeCode(~crossT & crossS)=2;

    % 3 Redundant
    routeCode(crossT & crossS)=3;

    % 4 Joint-required
    routeCode(~crossT & ~crossS & crossTS)=4;

    % 5 Resistant
    routeCode(~crossTS)=5;

    if any(routeCode==0)
        error('Unclassified cell detected.');
    end

    routeFrac=arrayfun(@(r) mean(routeCode==r),1:5);

    R=struct();
    R.FPT_T=FPT_T;
    R.FPT_S=FPT_S;
    R.FPT_TS=FPT_TS;
    R.routeCode=routeCode;
    R.routeFrac=routeFrac;
    R.Pcross60=mean(crossTS);
    R.RMST60=mean(min(FPT_TS,Tobs));
end


function R = evaluateFourBackgrounds(IT_C,IT_G,IS_U,IS_F,meso,dt,Tobs)
    % Evaluate the four microscopic backgrounds from paired T-S source rows.
    assert(isequal(size(IT_C),size(IT_G),size(IS_U),size(IS_F)), ...
        'All paired source matrices must have identical dimensions.');

    UT_C = meso.omegaT*IT_C;
    UT_G = meso.omegaT*IT_G;
    US_U = meso.omegaS*IS_U;
    US_F = meso.omegaS*IS_F;

    % Source-only FPTs need to be computed only once per source regime.
    FPT_TC = propagateLPOExact(UT_C,meso.rhoL,meso.ML,meso.L0,dt,Tobs);
    FPT_TG = propagateLPOExact(UT_G,meso.rhoL,meso.ML,meso.L0,dt,Tobs);
    FPT_SU = propagateLPOExact(US_U,meso.rhoL,meso.ML,meso.L0,dt,Tobs);
    FPT_SF = propagateLPOExact(US_F,meso.rhoL,meso.ML,meso.L0,dt,Tobs);

    FPT_CU = propagateLPOExact(UT_C+US_U,meso.rhoL,meso.ML,meso.L0,dt,Tobs);
    FPT_GU = propagateLPOExact(UT_G+US_U,meso.rhoL,meso.ML,meso.L0,dt,Tobs);
    FPT_CF = propagateLPOExact(UT_C+US_F,meso.rhoL,meso.ML,meso.L0,dt,Tobs);
    FPT_GF = propagateLPOExact(UT_G+US_F,meso.rhoL,meso.ML,meso.L0,dt,Tobs);

    Rcell=cell(4,1);
    Rcell{1}=assembleFateResult(FPT_TC,FPT_SU,FPT_CU,Tobs);
    Rcell{2}=assembleFateResult(FPT_TG,FPT_SU,FPT_GU,Tobs);
    Rcell{3}=assembleFateResult(FPT_TC,FPT_SF,FPT_CF,Tobs);
    Rcell{4}=assembleFateResult(FPT_TG,FPT_SF,FPT_GF,Tobs);
    R=vertcat(Rcell{:});
end

function R = assembleFateResult(FPT_T,FPT_S,FPT_TS,Tobs)
    crossT  = FPT_T<=Tobs;
    crossS  = FPT_S<=Tobs;
    crossTS = FPT_TS<=Tobs;

    % Exact LPO comparison principle audit.
    if any((crossT | crossS) & ~crossTS)
        error('Monotonicity violation: a source-only crossing was lost after T+S.');
    end
    if any(FPT_TS(isfinite(FPT_T)) > FPT_T(isfinite(FPT_T)) + 1e-10) || ...
       any(FPT_TS(isfinite(FPT_S)) > FPT_S(isfinite(FPT_S)) + 1e-10)
        error('FPT ordering violation in T+S versus source-only inputs.');
    end

    routeCode=zeros(size(FPT_TS));
    routeCode(crossT & ~crossS)=1;                  % T-sufficient
    routeCode(~crossT & crossS)=2;                  % S-sufficient
    routeCode(crossT & crossS)=3;                   % Redundant
    routeCode(~crossT & ~crossS & crossTS)=4;       % Joint-required
    routeCode(~crossTS)=5;                          % Resistant

    if any(routeCode==0)
        error('Unclassified fate-route pair detected.');
    end

    R=struct();
    R.FPT_T=FPT_T;
    R.FPT_S=FPT_S;
    R.FPT_TS=FPT_TS;
    R.routeCode=routeCode;
    R.routeFrac=arrayfun(@(rr) mean(routeCode==rr),1:5);
    R.Pcross60=mean(crossTS);
    R.RMST60=mean(min(FPT_TS,Tobs));
end

function idx = balancedSourceIndices(nBank,nPairs,seed)
    % Randomized balanced reuse: each bank member is used floor/ceil times.
    rng(seed,'twister');
    idx=zeros(nPairs,1);
    pos=1;
    while pos<=nPairs
        p=randperm(nBank);
        take=min(nBank,nPairs-pos+1);
        idx(pos:pos+take-1)=p(1:take);
        pos=pos+take;
    end
end

function FPT = propagateLPOExact(U,rho,ML,L0,dt,Tobs)
    [n,nBins]=size(U);
    L=L0*ones(n,1);
    FPT=inf(n,1);

    for b=1:nBins
        Ub=max(U(:,b),0);
        a=Ub+rho;

        Lnext=L;

        activeA=a>eps;
        if any(activeA)
            aa=a(activeA);
            uu=Ub(activeA);
            Lss=uu./aa;
            E=exp(-aa*dt);
            Lnext(activeA)=Lss+(L(activeA)-Lss).*E;
        end

        % a~0 means U=rho=0, hence L is constant.
        Lnext=min(max(Lnext,0),1);

        cross=isinf(FPT) & (L<ML) & (Lnext>=ML);
        if any(cross)
            idx=find(cross);
            aa=a(idx);
            uu=Ub(idx);
            Lss=uu./aa;

            ratio=(ML-Lss)./(L(idx)-Lss);
            ratio=max(min(ratio,1),realmin);
            tau=-log(ratio)./aa;
            tau=max(min(tau,dt),0);

            FPT(idx)=(b-1)*dt+tau;
        end

        L=Lnext;
    end

    FPT(FPT>Tobs)=inf;
end

