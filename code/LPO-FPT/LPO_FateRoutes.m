%% Fig4B_MesoscopicFateRoutes_FINAL.m
% =========================================================================
% Fig. 4B | Distinct routes to ferroptotic commitment
%
% Scientific question
% -------------------
% Given one simulated cell with one cytosolic temporal ROS history and one
% mitochondrial spatial ROS history, does ferroptotic commitment arise from:
%
%   1) T-sufficient    : temporal input alone crosses the fixed LPO boundary;
%   2) S-sufficient    : spatial/mitochondrial input alone crosses;
%   3) Redundant       : either source alone is sufficient;
%   4) Joint-required  : neither source alone crosses, but T+S crosses;
%   5) Resistant       : even T+S does not cross within Tobs.
%
% The same cell is therefore evaluated under three counterfactual inputs:
%
%   T only : U_T(t)  = omega_T I_T(t)
%   S only : U_S(t)  = omega_S I_S(t)
%   T + S  : U_TS(t) = U_T(t) + U_S(t)
%
% and all three are propagated through the SAME mesoscopic model:
%
%   dL/dt = U(t)(1-L) - rho_L L,
%   T_F   = inf{t >= 0 : L(t) >= M_L}.
%
% Four microscopic backgrounds are evaluated:
%
%   CU = CIR     + Uniform RDME
%   GU = GammaOU + Uniform RDME
%   CF = CIR     + Full SD-RDME
%   GF = GammaOU + Full SD-RDME
%
% MAIN FIGURE
% -----------
% Left   : ferroptosis FPT CDF for the four full-input backgrounds.
% Middle : RMST_60 with bootstrap 95% CI.
% Right  : population fractions of the five fate routes.
%
% IMPORTANT MODELING CHOICES
% --------------------------
% 1) TD-CME kernel and parameters are inherited from the finalized Fig. 2
%    strict TD-CME implementation:
%      N=1200; dt=2 s; Tobs=60 min;
%      CIR exact transition;
%      GammaOU exact decay + jump-time integral;
%      integrated-hazard binomial reaction updates.
%
% 2) The SD-RDME geometry/fields/global matching are NOT reconstructed from
%    scratch. They are loaded from:
%
%      Fig3BC_predictorIndependent_data.mat
%
%    generated by the finalized predictor-independent Fig. 3B-C script.
%    This keeps the current geometry, Full-vs-Uniform global matching,
%    window radius and kinetic parameters exactly locked.
%
% 3) The mitochondrial cell-scale input uses the predictor-independent
%    fixed-radius windows W_k from Fig. 3B-C, with NO A_q/top-q selection.
%    For each time bin:
%
%      j_k(t) = window R1 events / (|W_k| Delta t)
%
%      I_S(t) = sqrt( mean_k[ j_k(t)^2 ] ).
%
% 4) Source normalization is fixed across all microscopic conditions:
%
%      B_T = analytic stationary mean TD-CME Fenton flux (events/min)
%      B_S = independent Uniform-RDME calibration mean of I_S
%
%      I_T <- I_T / B_T
%      I_S <- I_S / B_S
%
%    No CIR/GammaOU-specific or Uniform/Full-specific rescaling is allowed.
%
% 5) The reference mesoscopic operating point is fixed BEFORE evaluation:
%
%      M_L = 0.50
%      tau_L = 1/rho_L = 10 min
%      eta = omega_S/omega_T = 1
%
%    The combined mean reference drive is set close to, but slightly below,
%    the deterministic constant-input commitment boundary:
%
%      U_crit = rho_L M_L/(1-M_L)
%      E[U_CU] / U_crit = meanDriveOverCritical = 0.95
%
%    This is an operational near-threshold reference point, not a fitted
%    biological constant. M_L, tau_L, eta and this operating-point ratio
%    should later be tested in SI robustness analyses rather than retuned
%    condition-by-condition.
%
% 6) LPO propagation uses the exact constant-input solution in every time
%    bin; no Euler approximation is used. Threshold crossing time inside a
%    bin is also solved analytically.
%
% 7) Because U_TS >= U_T and U_TS >= U_S pathwise and the LPO model is
%    order-preserving, every T- or S-sufficient cell MUST also cross under
%    T+S. The code audits this monotonicity and stops on violation.
%
% WORKFLOW
% --------
%   RUN_MODE = 'smoke'  -> structural test
%   RUN_MODE = 'pilot'  -> large TD bank + TD convergence + decoupled TD/SD source integration
%   RUN_MODE = 'final'  -> manuscript result after the TD convergence gate passes
%
% REQUIREMENTS
% ------------
% - Statistics and Machine Learning Toolbox
% - Parallel Computing Toolbox is optional.
%
% =========================================================================

clear; close all; clc;
clear functions;

%% ------------------------------ Configuration ----------------------------
RUN_MODE = 'final';          % 'smoke' | 'pilot' | 'final'

% Parallel execution is requested, but the code automatically falls back
% to serial execution when the current Windows project / JobStorage path
% contains non-ASCII characters. This avoids the MATLAB local-profile error:
%   "Invalid character code sequence detected."
%
% With the current Chinese project path, leave these settings unchanged:
% the preflight check will use serial loops safely. To enable parfor later,
% move the project to an ASCII-only folder and optionally set an ASCII-only
% JobStorageLocation below.
USE_PARALLEL    = true;
AUTO_START_POOL = true;
N_WORKERS       = 8;
PARALLEL_JOB_STORAGE = '';   % e.g. 'D:\\MATLAB_JobStorage' after moving project

SAVE_FIG  = true;
SAVE_DATA = true;
SAVE_CSV  = true;
EXPORT_DPI = 600;

% Locked input generated by finalized Fig. 3B-C code.
SD_DATA_NAME = 'Fig3BC_predictorIndependent_data.mat';

% Optional finalized Fig. 2 MAT file. If absent, locked parameters below
% are used exactly.
TD_DATA_NAME = 'TDCME_Fig2ABC_results_final.mat';

% Mesoscopic reference parameters.
meso.ML = 0.50;
meso.tauL_min = 10.0;
meso.rhoL = 1/meso.tauL_min;        % min^-1
meso.L0 = 0.0;
meso.eta_ST = 1.0;                  % omega_S / omega_T
meso.meanDriveOverCritical = 0.95;  % E[U_CU] / Ucrit reference

% Common observation/mesoscopic binning.
Tobs_min = 60.0;
dtBin_min = 0.50;                   % locked to current SD-RDME recording scale
tEdges = 0:dtBin_min:Tobs_min;
nBins = numel(tEdges)-1;

alphaCI = 0.05;

switch lower(RUN_MODE)
    case 'smoke'
        cfg.nCalSpatial = 12;
        cfg.nSD         = 30;        % expensive spatial source bank
        cfg.nTD         = 1000;      % cheap temporal source bank
        cfg.nMesoPairs  = 1000;      % synthetic independent T-S pairings
        cfg.nBoot       = 100;
        cfg.nBootPairs  = 500;       % pairings regenerated per source bootstrap
        cfg.tdConvN     = [100 300 1000];
        cfg.nConvRep    = 100;

    case 'pilot'
        cfg.nCalSpatial = 50;
        cfg.nSD         = 120;
        cfg.nTD         = 5000;
        cfg.nMesoPairs  = 5000;
        cfg.nBoot       = 500;
        cfg.nBootPairs  = 1000;
        cfg.tdConvN     = [100 300 1000 3000 5000];
        cfg.nConvRep    = 100;

    case 'final'
        cfg.nCalSpatial = 100;
        cfg.nSD         = 300;
        cfg.nTD         = 12000;
        cfg.nMesoPairs  = 12000;
        cfg.nBoot       = 1000;
        cfg.nBootPairs  = 2000;
        cfg.tdConvN     = [300 1000 3000 5000 8000 12000];
        cfg.nConvRep    = 100;

    otherwise
        error('RUN_MODE must be smoke, pilot, or final.');
end

% Numerical convergence gate.  These are audit tolerances, not biological
% effect-size thresholds.  The final run is blocked only if the large TD
% bank is still numerically unstable or grossly inconsistent with the
% low-order matching established in Fig. 2.
cfg.tdStableRelTol = 0.03;  % <3% change between the last two convergence sizes
cfg.tdMeanMatchTol = 0.05;  % G/C mean-input ratio within 5% of 1
cfg.strictFinalTDGate = true;

cfg.seedTD       = 20260821;
cfg.seedSDcal    = 20260822;
cfg.seedSDeval   = 20260823;
cfg.seedBoot     = 20260824;
cfg.seedPairTD   = 20260825;
cfg.seedPairSD   = 20260826;
cfg.seedTDconv   = 20260827;

scriptDir = fileparts(mfilename('fullpath'));
if isempty(scriptDir), scriptDir = pwd; end
outDir = fullfile(scriptDir, ['Fig4B_fate_routes_' lower(RUN_MODE)]);
if ~exist(outDir,'dir'), mkdir(outDir); end

outStem = fullfile(outDir,'Fig4B_fateRoutes_main');
outMAT  = fullfile(outDir,'Fig4B_fateRoutes_data.mat');
outSummaryCSV = fullfile(outDir,'Fig4B_fateRoutes_summary.csv');
outCellCSV    = fullfile(outDir,'Fig4B_fateRoutes_cells.csv');

% Spatial-interface diagnostics used to decide whether RMS coarse-graining
% preserves risk-relevant Uniform-vs-Full differences before FINAL.
outDiagStem   = fullfile(outDir,'Fig4B_spatialInterface_diagnostic');
outDiagCSV    = fullfile(outDir,'Fig4B_spatialInterface_diagnostic_summary.csv');
outDiagCellCSV= fullfile(outDir,'Fig4B_spatialInterface_diagnostic_cells.csv');

% TD -> L decoder diagnostics used to resolve the CIR/GammaOU rank reversal
% observed in the pilot before committing computational resources to FINAL.
outTDDiagStem    = fullfile(outDir,'Fig4B_TDtoL_decoder_diagnostic');
outTDDiagCSV     = fullfile(outDir,'Fig4B_TDtoL_decoder_diagnostic_summary.csv');
outTDDiagCellCSV = fullfile(outDir,'Fig4B_TDtoL_decoder_diagnostic_cells.csv');

% TD Monte-Carlo convergence audit.
outTDConvStem = fullfile(outDir,'Fig4B_TD_convergence_audit');
outTDConvCSV  = fullfile(outDir,'Fig4B_TD_convergence_audit.csv');

%% ------------------------------ Figure style -----------------------------
set(groot,'defaultFigureColor','w');
set(groot,'defaultAxesFontName','Arial');
set(groot,'defaultTextFontName','Arial');
set(groot,'defaultAxesFontSize',7);
set(groot,'defaultTextFontSize',7);
set(groot,'defaultAxesLineWidth',0.70);
set(groot,'defaultLineLineWidth',1.05);
set(groot,'defaultAxesTickDir','out');
set(groot,'defaultAxesBox','on');
set(groot,'defaultLegendInterpreter','tex');
set(groot,'defaultAxesTickLabelInterpreter','tex');

colCond = [ ...
    0.38 0.40 0.43;   % CU gray
    0.82 0.32 0.24;   % GU vermillion
    0.16 0.43 0.70;   % CF blue
    0.48 0.24 0.62];  % GF purple

condNames  = {'CU','GU','CF','GF'};
condLabels = {'CIR + Uniform','GammaOU + Uniform', ...
              'CIR + Full','GammaOU + Full'};

routeNames = {'T-sufficient','S-sufficient','Redundant', ...
              'Joint-required','Resistant'};
routeColors = [ ...
    0.25 0.49 0.72;   % T-sufficient
    0.19 0.60 0.55;   % S-sufficient
    0.53 0.38 0.67;   % redundant
    0.93 0.66 0.20;   % joint-required
    0.82 0.83 0.84];  % resistant

%% ---------------------- Resolve/load locked source models ----------------
sdFile = resolveInputFile(scriptDir,SD_DATA_NAME);
if isempty(sdFile)
    error(['Required SD-RDME data file not found: %s\n' ...
           'Run the finalized SDRDME_burdenandFPT script first so that\n' ...
           'Fig3BC_predictorIndependent_data.mat is available.'],SD_DATA_NAME);
end

fprintf('============================================================\n');
fprintf('Fig. 4B | Mesoscopic fate-route analysis (%s)\n',upper(RUN_MODE));
fprintf('============================================================\n');
fprintf('Loading locked SD-RDME data:\n  %s\n',sdFile);

SD = load(sdFile);

requiredSD = {'meta','x','y','mask','S','G','c1_sd','D_Fe2_sd'};
for k = 1:numel(requiredSD)
    if ~isfield(SD,requiredSD{k})
        error('SD data file is missing required variable: %s',requiredSD{k});
    end
end

% Locked current spatial geometry.
xCoord = SD.x(:).';
yCoord = SD.y(:).';
mask = logical(SD.mask);
[Xg,Yg] = meshgrid(xCoord,yCoord); %#ok<ASGLU>
K = nnz(mask);

if isfield(SD.meta,'Tobs')
    assert(abs(SD.meta.Tobs-Tobs_min)<1e-12, ...
        'SD data Tobs must equal %.1f min.',Tobs_min);
end
if isfield(SD.meta,'dtRecord')
    assert(abs(SD.meta.dtRecord-dtBin_min)<1e-12, ...
        'This script expects dtBin=SD dtRecord=%.3f min.',SD.meta.dtRecord);
end

Psd = SD.meta.parameters;
D0_Fe2 = Psd.D0_Fe2;
if isfield(Psd,'D0_Fe3')
    D0_Fe3 = Psd.D0_Fe3;
else
    D0_Fe3 = 0.70*D0_Fe2;
end
c2_0 = Psd.c2_0;
FeTot_per_voxel = Psd.FeTot_per_voxel;
fracFe2_0 = Psd.fracFe2_0;

windowRadius = SD.meta.windowRadius;
alphaMatch = SD.meta.alphaMatch;

G = SD.G;
c1FullMap = SD.c1_sd;
D1FullMap = SD.D_Fe2_sd;
D2FullMap = D0_Fe3 .* G;
D2FullMap(~mask) = NaN;

c1F = c1FullMap(mask);
c2F = c2_0*ones(K,1);
D1F = D1FullMap(mask);
D2F = D2FullMap(mask);

% Rebuild Uniform exactly as in current Fig. 3B-C.
D1Umap = NaN(size(D1FullMap));
D2Umap = NaN(size(D2FullMap));
D1Umap(mask) = mean(D1F);
D2Umap(mask) = mean(D2F);

c1U = alphaMatch * mean(c1F) * ones(K,1);
c2U = c2_0 * ones(K,1);

idxMap = buildMaskIndexMap(mask);
dx = mean(diff(xCoord));
dy = mean(diff(yCoord));

[fromF1,toF1,qF1] = buildDirectedEdgesHarmonic(mask,idxMap,D1FullMap,dx,dy);
[fromF2,toF2,qF2] = buildDirectedEdgesHarmonic(mask,idxMap,D2FullMap,dx,dy);
[fromU1,toU1,qU1] = buildDirectedEdgesHarmonic(mask,idxMap,D1Umap,dx,dy);
[fromU2,toU2,qU2] = buildDirectedEdgesHarmonic(mask,idxMap,D2Umap,dx,dy);

outF = buildOutgoingLists(K,fromF1,toF1,qF1,fromF2,toF2,qF2);
outU = buildOutgoingLists(K,fromU1,toU1,qU1,fromU2,toU2,qU2);

coordX = Xg(mask);
coordY = Yg(mask);
win = buildCircularWindowsSparse(coordX,coordY,windowRadius);

N0 = FeTot_per_voxel * ones(K,1);
x1_0_SD = round(fracFe2_0*N0);
x2_0_SD = N0-x1_0_SD;

fprintf('Locked SD grid             = %d x %d, K=%d\n', ...
    numel(xCoord),numel(yCoord),K);
fprintf('Locked window radius       = %.3f\n',windowRadius);
fprintf('Locked Uniform alphaMatch  = %.6f\n',alphaMatch);

%% ---------------------- Load/lock TD-CME parameters ----------------------
tdFile = resolveInputFile(scriptDir,TD_DATA_NAME);
if ~isempty(tdFile)
    fprintf('Loading finalized TD-CME parameter file:\n  %s\n',tdFile);
    DTD = load(tdFile);
    if ~isfield(DTD,'SAVE') || ~isfield(DTD.SAVE,'parameters')
        error('TD MAT file does not contain SAVE.parameters.');
    end
    p = DTD.SAVE.parameters;
else
    fprintf(['Finalized TD-CME MAT file not found; using the exact locked Fig. 2 ' ...
             'parameters embedded below.\n']);
    p = struct();
    p.N = 1200;
    p.kappa1 = 3.0e-4;
    p.shape1 = 0.20;
    p.mu_c1  = 1.5e-5;
    p.theta1 = p.mu_c1/p.shape1;
    p.a1     = p.shape1*p.kappa1;

    p.kappa2 = 4.0e-4;
    p.shape2 = 3.50;
    p.mu_c2  = 1.7e-5;
    p.theta2 = p.mu_c2/p.shape2;
    p.a2     = p.shape2*p.kappa2;
end

% Fill derived TD quantities if absent.
p.lambda = p.mu_c1+p.mu_c2;
p.p_x1_ss = p.mu_c2/p.lambda;
p.x1_ss = p.N*p.p_x1_ss;
p.x2_ss = p.N-p.x1_ss;
p.v_eff = p.mu_c1*p.x1_ss;   % expected R1 events / s

td.dt_s = 2.0;
td.T_s  = Tobs_min*60;
td.bin_s = dtBin_min*60;

assert(abs(td.T_s/td.dt_s-round(td.T_s/td.dt_s))<1e-12);
assert(abs(td.bin_s/td.dt_s-round(td.bin_s/td.dt_s))<1e-12);

fprintf('Locked TD N                = %d\n',p.N);
fprintf('Locked TD dt               = %.1f s\n',td.dt_s);
fprintf('Common mesoscopic bin      = %.2f min\n',dtBin_min);

%% ----------------------- Optional parallel configuration -----------------
usePar = configureParallel(USE_PARALLEL,AUTO_START_POOL,N_WORKERS, ...
    PARALLEL_JOB_STORAGE,scriptDir);
fprintf('Parallel spatial SSA       = %d\n',usePar);

%% ----------------------- Fixed source normalization ----------------------
% TD scale is analytic and independent of sampled trajectories.
B_T = p.v_eff*60;  % events / min

% SD scale is obtained from an INDEPENDENT Uniform-RDME calibration bank.
fprintf('\nIndependent Uniform-RDME spatial normalization calibration...\n');
IScalU_raw = simulateSpatialInputBankNSM(c1U,c2U,outU,win, ...
    x1_0_SD,x2_0_SD,tEdges,cfg.nCalSpatial,cfg.seedSDcal,usePar);

B_S = mean(IScalU_raw(:));
if ~(isfinite(B_S) && B_S>0)
    error('Invalid spatial normalization B_S.');
end

fprintf('B_T (analytic TD reference) = %.6g events/min\n',B_T);
fprintf('B_S (independent U-RDME RMS reference) = %.6g events/(voxel min)\n',B_S);

%% ----------------------- Fixed mesoscopic operating point ----------------
Ucrit = meso.rhoL*meso.ML/(1-meso.ML);

% Since the normalized CU means are approximately one for each source,
% omega_T + omega_S is fixed to a prespecified fraction of Ucrit.
meso.omegaT = meso.meanDriveOverCritical*Ucrit/(1+meso.eta_ST);
meso.omegaS = meso.eta_ST*meso.omegaT;

fprintf('\nMesoscopic reference operating point:\n');
fprintf('  M_L                         = %.3f\n',meso.ML);
fprintf('  tau_L                       = %.3f min\n',meso.tauL_min);
fprintf('  rho_L                       = %.5f min^-1\n',meso.rhoL);
fprintf('  eta = omega_S/omega_T       = %.3f\n',meso.eta_ST);
fprintf('  U_crit                      = %.5f min^-1\n',Ucrit);
fprintf('  target mean U_CU/Ucrit      = %.3f\n',meso.meanDriveOverCritical);
fprintf('  omega_T                     = %.5f min^-1\n',meso.omegaT);
fprintf('  omega_S                     = %.5f min^-1\n',meso.omegaS);

%% ----------------------- Generate evaluation trajectory banks ------------
fprintf('\nGenerating strict TD-CME input bank (nTD = %d)...\n',cfg.nTD);
[IT_C_raw,IT_G_raw] = simulateTDInputBank(p,td,cfg.nTD,cfg.seedTD);

fprintf('\nGenerating exact Uniform-RDME spatial input bank...\n');
% Common random-number seed family is deliberately shared between U and F
% to reduce Monte Carlo variance in paired model contrasts.
IS_U_raw = simulateSpatialInputBankNSM(c1U,c2U,outU,win, ...
    x1_0_SD,x2_0_SD,tEdges,cfg.nSD,cfg.seedSDeval,usePar);

fprintf('\nGenerating exact Full SD-RDME spatial input bank...\n');
IS_F_raw = simulateSpatialInputBankNSM(c1F,c2F,outF,win, ...
    x1_0_SD,x2_0_SD,tEdges,cfg.nSD,cfg.seedSDeval,usePar);

% Fixed, source-level normalization.
IT_C = IT_C_raw/B_T;
IT_G = IT_G_raw/B_T;
IS_U = IS_U_raw/B_S;
IS_F = IS_F_raw/B_S;

fprintf('\nNormalized input audit (mean over cells and time):\n');
fprintf('  E[I_T | CIR]      = %.4f\n',mean(IT_C(:)));
fprintf('  E[I_T | GammaOU]  = %.4f\n',mean(IT_G(:)));
fprintf('  E[I_S | Uniform]  = %.4f\n',mean(IS_U(:)));
fprintf('  E[I_S | Full]     = %.4f\n',mean(IS_F(:)));

%% ---------------- Spatial-interface diagnostics for PILOT ----------------
% These diagnostics DO NOT alter the mesoscopic model or any input.
% They test whether the prespecified RMS operator retains enough of the
% Full-vs-Uniform spatial signal to justify proceeding to FINAL.
%
% Required quantities:
%   1) pooled mean E[I_S]
%   2) pooled CV and median within-cell temporal CV
%   3) pooled Q90 and Q95
%   4) cell-integrated spatial dose D_S = integral_0^T I_S(t) dt
%
% Because U and F use the same random-seed family, paired cell-level
% differences are also reported as a Monte-Carlo diagnostic.

DIAG_U = summarizeSpatialInput(IS_U,dtBin_min);
DIAG_F = summarizeSpatialInput(IS_F,dtBin_min);

spatialDiagSummary = table( ...
    string({'Uniform';'Full'}), ...
    [DIAG_U.meanPooled; DIAG_F.meanPooled], ...
    [DIAG_U.cvPooled; DIAG_F.cvPooled], ...
    [DIAG_U.q90Pooled; DIAG_F.q90Pooled], ...
    [DIAG_U.q95Pooled; DIAG_F.q95Pooled], ...
    [DIAG_U.medianCellCV; DIAG_F.medianCellCV], ...
    [DIAG_U.meanDose; DIAG_F.meanDose], ...
    [DIAG_U.medianDose; DIAG_F.medianDose], ...
    [DIAG_U.q90Dose; DIAG_F.q90Dose], ...
    [DIAG_U.q95Dose; DIAG_F.q95Dose], ...
    'VariableNames',{ ...
    'SpatialCondition','Mean_IS','PooledCV_IS','Q90_IS','Q95_IS', ...
    'MedianWithinCellCV_IS','MeanDose_DS','MedianDose_DS', ...
    'Q90Dose_DS','Q95Dose_DS'});

ratioMean = DIAG_F.meanPooled/max(DIAG_U.meanPooled,eps);
ratioCV   = DIAG_F.cvPooled/max(DIAG_U.cvPooled,eps);
ratioQ90  = DIAG_F.q90Pooled/max(DIAG_U.q90Pooled,eps);
ratioQ95  = DIAG_F.q95Pooled/max(DIAG_U.q95Pooled,eps);
ratioDose = DIAG_F.meanDose/max(DIAG_U.meanDose,eps);

deltaDose = DIAG_F.cellDose-DIAG_U.cellDose;
deltaCellQ95 = DIAG_F.cellQ95-DIAG_U.cellQ95;

fprintf('\n================ Spatial RMS-interface diagnostic ================\n');
fprintf('                                Uniform        Full       F/U ratio\n');
fprintf('Mean I_S                      %10.4f  %10.4f    %8.4f\n', ...
    DIAG_U.meanPooled,DIAG_F.meanPooled,ratioMean);
fprintf('Pooled CV(I_S)                %10.4f  %10.4f    %8.4f\n', ...
    DIAG_U.cvPooled,DIAG_F.cvPooled,ratioCV);
fprintf('Pooled Q90(I_S)               %10.4f  %10.4f    %8.4f\n', ...
    DIAG_U.q90Pooled,DIAG_F.q90Pooled,ratioQ90);
fprintf('Pooled Q95(I_S)               %10.4f  %10.4f    %8.4f\n', ...
    DIAG_U.q95Pooled,DIAG_F.q95Pooled,ratioQ95);
fprintf('Median within-cell temporal CV%10.4f  %10.4f\n', ...
    DIAG_U.medianCellCV,DIAG_F.medianCellCV);
fprintf('Mean D_S = int I_S dt         %10.4f  %10.4f    %8.4f\n', ...
    DIAG_U.meanDose,DIAG_F.meanDose,ratioDose);
fprintf('Median D_S                    %10.4f  %10.4f\n', ...
    DIAG_U.medianDose,DIAG_F.medianDose);
fprintf('Q95(D_S)                      %10.4f  %10.4f\n', ...
    DIAG_U.q95Dose,DIAG_F.q95Dose);
fprintf('Paired mean [D_S^F-D_S^U]     = %.4f\n',mean(deltaDose));
fprintf('Paired fraction D_S^F>D_S^U  = %.3f\n',mean(deltaDose>0));
fprintf('Paired mean [Q95cell^F-Q95cell^U] = %.4f\n',mean(deltaCellQ95));
fprintf('Paired fraction Q95cell^F>Q95cell^U = %.3f\n',mean(deltaCellQ95>0));
fprintf('==================================================================\n');

spatialDiagCellTable = table( ...
    (1:cfg.nSD)', ...
    DIAG_U.cellMean,DIAG_F.cellMean, ...
    DIAG_U.cellCV,DIAG_F.cellCV, ...
    DIAG_U.cellQ90,DIAG_F.cellQ90, ...
    DIAG_U.cellQ95,DIAG_F.cellQ95, ...
