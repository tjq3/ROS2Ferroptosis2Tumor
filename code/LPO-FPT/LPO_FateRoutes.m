    B.CI_Hmax=quantileLocal(bHmax,[alpha/2 1-alpha/2]);
    B.CI_Lmax=quantileLocal(bLmax,[alpha/2 1-alpha/2]);
    B.CI_PcrossT=quantileLocal(bP,[alpha/2 1-alpha/2]);
    B.CI_RMSTT=quantileLocal(bRMST,[alpha/2 1-alpha/2]);

    B.bootDose=bDose;
    B.bootQ95=bQ95;
    B.bootMaxWindow=bMaxWindow;
    B.bootHmax=bHmax;
    B.bootLmax=bLmax;
    B.bootPcrossT=bP;
    B.bootRMSTT=bRMST;
end


function C = tdConvergenceAudit(CIR,GOU,nGrid,nRep,seed,stableTol,matchTol)
    % Convergence audit from per-cell summaries of one large matched TD bank.
    % At each n < nBank, repeated matched subsets are drawn without
    % replacement. CIR and GammaOU always use the same cell indices.
    rng(seed,'twister');

    N=numel(CIR.cellDose);
    nGrid=unique(nGrid(:)');
    nGrid=nGrid(nGrid<=N);
    if isempty(nGrid) || nGrid(end)~=N
        nGrid=[nGrid N];
    end

    cellMeanC=CIR.cellDose/60;
    cellMeanG=GOU.cellDose/60;

    fieldsC={cellMeanC,CIR.cellQ95,CIR.cellMaxWindowDose,CIR.cellHmax};
    fieldsG={cellMeanG,GOU.cellQ95,GOU.cellMaxWindowDose,GOU.cellHmax};

    nM=numel(nGrid);
    med=zeros(nM,4);
    lo=zeros(nM,4);
    hi=zeros(nM,4);

    for ii=1:nM
        nn=nGrid(ii);
        RR=zeros(nRep,4);

        if nn==N
            for mm=1:4
                RR(:,mm)=mean(fieldsG{mm})/max(mean(fieldsC{mm}),eps);
            end
        else
            for rr=1:nRep
                idx=randperm(N,nn);
                for mm=1:4
                    RR(rr,mm)=mean(fieldsG{mm}(idx))/ ...
                        max(mean(fieldsC{mm}(idx)),eps);
                end
            end
        end

        for mm=1:4
            med(ii,mm)=median(RR(:,mm));
            q=quantileLocal(RR(:,mm),[0.025 0.975]);
            lo(ii,mm)=q(1);
            hi(ii,mm)=q(2);
        end
    end

    C=struct();
    C.n=nGrid;
    C.meanRatio=med(:,1)';
    C.meanRatioLo=lo(:,1)';
    C.meanRatioHi=hi(:,1)';
    C.q95Ratio=med(:,2)';
    C.q95RatioLo=lo(:,2)';
    C.q95RatioHi=hi(:,2)';
    C.maxWinRatio=med(:,3)';
    C.maxWinRatioLo=lo(:,3)';
    C.maxWinRatioHi=hi(:,3)';
    C.hmaxRatio=med(:,4)';
    C.hmaxRatioLo=lo(:,4)';
    C.hmaxRatioHi=hi(:,4)';

    if numel(C.n)>=2
        C.lastStepRelChange=abs(C.meanRatio(end)-C.meanRatio(end-1))/ ...
            max(abs(C.meanRatio(end)),eps);
    else
        C.lastStepRelChange=Inf;
    end

    C.stableFlag=C.lastStepRelChange<stableTol;
    C.meanMatchFlag=abs(C.meanRatio(end)-1)<matchTol;
    C.pass=C.stableFlag && C.meanMatchFlag;
    C.stableTol=stableTol;
    C.meanMatchTol=matchTol;
end

function D = summarizeSpatialInput(I,dt)
    % Summary of a normalized cell-by-time spatial input matrix.
    % All condition comparisons are performed without any re-normalization.
    I=max(I,0);

    pooled=I(:);
    D.meanPooled=mean(pooled);
    D.stdPooled=std(pooled,0);
    D.cvPooled=D.stdPooled/max(D.meanPooled,eps);
    D.q90Pooled=quantileLocal(pooled,0.90);
    D.q95Pooled=quantileLocal(pooled,0.95);

    D.cellMean=mean(I,2);
    D.cellSD=std(I,0,2);
    D.cellCV=D.cellSD./max(D.cellMean,eps);
    D.cellQ90=rowQuantileLocal(I,0.90);
    D.cellQ95=rowQuantileLocal(I,0.95);
    D.cellDose=sum(I,2)*dt;

    D.medianCellCV=median(D.cellCV);
    D.meanDose=mean(D.cellDose);
    D.medianDose=median(D.cellDose);
    D.q90Dose=quantileLocal(D.cellDose,0.90);
    D.q95Dose=quantileLocal(D.cellDose,0.95);
end

function q = rowQuantileLocal(X,p)
    % Linear-interpolation quantile evaluated independently for each row.
    X=sort(X,2);
    n=size(X,2);
    pp=min(max(p,0),1);
    pos=1+pp*(n-1);
    lo=floor(pos);
    hi=ceil(pos);

    if lo==hi
        q=X(:,lo);
    else
        q=X(:,lo)+(pos-lo)*(X(:,hi)-X(:,lo));
    end
end

function [x,S] = empiricalSurvivalPositive(v)
    v=v(:);
    v=v(isfinite(v));
    v=sort(v);
    n=numel(v);
    if n==0
        x=NaN; S=NaN; return;
    end

    % Use unique support and exact empirical P(V >= x).
    [x,~,ic]=unique(v);
    counts=accumarray(ic,1);
    tailCounts=flipud(cumsum(flipud(counts)));
    S=tailCounts/n;

    % A log-y plot cannot display exactly zero; S is never zero here.
end

function [x,F] = empiricalCDFLocal(v)
    v=v(:);
    v=v(isfinite(v));
    v=sort(v);
    n=numel(v);
    if n==0
        x=NaN; F=NaN; return;
    end
    [x,~,ic]=unique(v);
    counts=accumarray(ic,1);
    F=cumsum(counts)/n;
end

function q = quantileLocal(x,p)
    x=sort(x(:));
    n=numel(x);
    p=p(:).';

    q=nan(size(p));
    if n==0, return; end

    for j=1:numel(p)
        pp=min(max(p(j),0),1);
        pos=1+pp*(n-1);
        lo=floor(pos);
        hi=ceil(pos);
        if lo==hi
            q(j)=x(lo);
        else
            q(j)=x(lo)+(pos-lo)*(x(hi)-x(lo));
        end
    end
end

function formatAxes(ax)
    set(ax,'Box','on','LineWidth',0.70,'TickDir','out','Layer','top', ...
        'FontSize',7,'XColor',[0.08 0.08 0.08], ...
        'YColor',[0.08 0.08 0.08]);
end
