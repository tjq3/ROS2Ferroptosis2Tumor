function [from,to,q] = buildDirectedEdgesHarmonic(mask,idxMap,Dfield,dx,dy)
    [nRows,nCols]=size(mask);
    from=[]; to=[]; q=[];
    dirs=[0 1;0 -1;1 0;-1 0];

    for r=1:nRows
        for c=1:nCols
            if ~mask(r,c), continue; end
            k=idxMap(r,c);

            for d=1:4
                rr=r+dirs(d,1);
                cc=c+dirs(d,2);
                if rr<1 || rr>nRows || cc<1 || cc>nCols || ~mask(rr,cc)
                    continue;
                end

                l=idxMap(rr,cc);
                Dk=Dfield(r,c);
                Dl=Dfield(rr,cc);
                Dij=2*Dk*Dl/max(Dk+Dl,eps);

                if dirs(d,1)==0
                    h2=dx^2;
                else
                    h2=dy^2;
                end

                from(end+1,1)=k; %#ok<AGROW>
                to(end+1,1)=l; %#ok<AGROW>
                q(end+1,1)=Dij/h2; %#ok<AGROW>
            end
        end
    end
end

function win = buildCircularWindowsSparse(coordX,coordY,radius)
    K=numel(coordX);
    I=cell(K,1);
    J=cell(K,1);
    members=cell(K,1);

    for k=1:K
        idx=find((coordX-coordX(k)).^2+(coordY-coordY(k)).^2 ...
            <= radius^2+1e-14);
        members{k}=idx(:);
        I{k}=repmat(k,numel(idx),1);
        J{k}=idx(:);
    end

    I=vertcat(I{:});
    J=vertcat(J{:});
    W=sparse(I,J,1,K,K);
    sizeVec=full(sum(W,2));

    centersByVoxel=cell(K,1);
    for j=1:K
        centersByVoxel{j}=find(W(:,j));
    end

    win.W=W;
    win.size=sizeVec;
    win.members=members;
    win.centersByVoxel=centersByVoxel;
end

function out = buildOutgoingLists(K,from1,to1,q1,from2,to2,q2)
    out.to1=cell(K,1);
    out.q1=cell(K,1);
    out.to2=cell(K,1);
    out.q2=cell(K,1);

    for e=1:numel(q1)
        k=from1(e);
        out.to1{k}(end+1,1)=to1(e); %#ok<AGROW>
        out.q1{k}(end+1,1)=q1(e); %#ok<AGROW>
    end
    for e=1:numel(q2)
        k=from2(e);
        out.to2{k}(end+1,1)=to2(e); %#ok<AGROW>
        out.q2{k}(end+1,1)=q2(e); %#ok<AGROW>
    end

    out.q1sum=zeros(K,1);
    out.q2sum=zeros(K,1);
    for k=1:K
        out.q1sum(k)=sum(out.q1{k});
        out.q2sum(k)=sum(out.q2{k});
    end
end

function [voxelRate,tree] = refreshVoxelRates(touched,voxelRate,tree, ...
        x1,x2,c1,c2,q1sum,q2sum)
    for ii=1:numel(touched)
        k=touched(ii);
        newRate=max(x1(k)*(c1(k)+q1sum(k))+ ...
                    x2(k)*(c2(k)+q2sum(k)),0);
        delta=newRate-voxelRate(k);
        voxelRate(k)=newRate;
        tree=fenwickAdd(tree,k,delta);
    end
end

function j = chooseDestination(to,q)
    if isempty(to)
        error('No outgoing destination available.');
    end
    if numel(to)==1
        j=to(1);
        return;
    end
    cs=cumsum(q);
    idx=find(cs>=rand*cs(end),1,'first');
    j=to(idx);
end

function tree = fenwickBuild(values)
    n=numel(values);
    tree=zeros(n,1);
    for i=1:n
        tree=fenwickAdd(tree,i,values(i));
    end
end

function tree = fenwickAdd(tree,idx,delta)
    n=numel(tree);
    while idx<=n
        tree(idx)=tree(idx)+delta;
        lowbit=idx-bitand(idx,idx-1);
        idx=idx+lowbit;
    end
end

function s = fenwickTotal(tree)
    idx=numel(tree);
    s=0;
    while idx>0
        s=s+tree(idx);
        lowbit=idx-bitand(idx,idx-1);
        idx=idx-lowbit;
    end
end

function idx = fenwickFind(tree,target)
    n=numel(tree);
    if target<=0, target=realmin; end
    idx=0;
    bit=2^floor(log2(n));

    while bit>0
        nxt=idx+bit;
        if nxt<=n && tree(nxt)<target
            idx=nxt;
            target=target-tree(nxt);
        end
        bit=floor(bit/2);
    end
    idx=min(idx+1,n);
end



function D = summarizeTDDecoder(I,dt,meso,Tobs)
    % Diagnose how temporal TD-CME input is transformed by the finite-memory
    % lipid-peroxidation decoder without changing any model parameter.
    I=max(I,0);
    [n,nBins]=size(I);

    % Basic path summaries.
    D.meanInput=mean(I(:));
    D.cellDose=sum(I,2)*dt;
    D.cellQ95=rowQuantileLocal(I,0.95);

    % Maximum cumulative input within one lipid-memory window tau_L.
    nWin=max(1,round(meso.tauL_min/dt));
    if nWin>=nBins
        D.cellMaxWindowDose=D.cellDose;
    else
        cs=[zeros(n,1), cumsum(I,2)*dt];
        winDose=cs(:,(nWin+1):(nBins+1))-cs(:,1:(nBins+1-nWin));
        D.cellMaxWindowDose=max(winDose,[],2);
    end

    % Exact discrete update of H' = I - H/tau_L for piecewise-constant I.
    decay=exp(-dt/meso.tauL_min);
    gain=meso.tauL_min*(1-decay);
    H=zeros(n,1);
    Hmax=zeros(n,1);

    % Actual nonlinear T-only lipid-peroxidation trajectory.
    L=meso.L0*ones(n,1);
    Lmax=L;
    FPT=inf(n,1);

    for b=1:nBins
        Ib=I(:,b);

        H=decay*H+gain*Ib;
        Hmax=max(Hmax,H);

        Ub=meso.omegaT*Ib;
        a=Ub+meso.rhoL;
        Lnext=L;

        activeA=a>eps;
        if any(activeA)
            aa=a(activeA);
            uu=Ub(activeA);
            Lss=uu./aa;
            E=exp(-aa*dt);
            Lnext(activeA)=Lss+(L(activeA)-Lss).*E;
        end

        Lnext=min(max(Lnext,0),1);

        crossed=isinf(FPT) & (L<meso.ML) & (Lnext>=meso.ML);
        if any(crossed)
            idx=find(crossed);
            aa=a(idx);
            uu=Ub(idx);
            Lss=uu./aa;

            ratio=(meso.ML-Lss)./(L(idx)-Lss);
            ratio=max(min(ratio,1),realmin);
            tauCross=-log(ratio)./aa;
            tauCross=max(min(tauCross,dt),0);
            FPT(idx)=(b-1)*dt+tauCross;
        end

        L=Lnext;
        Lmax=max(Lmax,L);
    end

    FPT(FPT>Tobs)=inf;

    D.cellHmax=Hmax;
    D.cellLmax=Lmax;
    D.FPT_T=FPT;

    D.meanDose=mean(D.cellDose);
    D.meanCellQ95=mean(D.cellQ95);
    D.meanMaxWindowDose=mean(D.cellMaxWindowDose);
    D.meanHmax=mean(D.cellHmax);
    D.meanLmax=mean(D.cellLmax);
    D.PcrossT=mean(D.FPT_T<=Tobs);
    D.RMSTT=mean(min(D.FPT_T,Tobs));
end

function B = bootstrapTDDecoderContrast(C,G,Tobs,nBoot,alpha,seed)
