function BOOT = bootstrapFateRoutesTwoSource( ...
        IT_C,IT_G,IS_U,IS_F,meso,dt,Tobs,tCDF,nBoot,nPairs,alpha,seed)

    rng(seed,'twister');

    nTD=size(IT_C,1);
    nSD=size(IS_U,1);
    nCond=4;
    nRoute=5;
    nT=numel(tCDF);

    rmstBoot=zeros(nBoot,nCond);
    pBoot=zeros(nBoot,nCond);
    routeBoot=zeros(nBoot,nCond,nRoute);
    cdfBoot=zeros(nBoot,nT,nCond);
    jointDelta=zeros(nBoot,1);

    for b=1:nBoot
        % Independent source-bank bootstrap, with matched regimes inside
        % each source family to preserve common-random-number contrasts.
        idxT=randi(nTD,nPairs,1);
        idxS=randi(nSD,nPairs,1);

        Rb=evaluateFourBackgrounds( ...
            IT_C(idxT,:),IT_G(idxT,:),IS_U(idxS,:),IS_F(idxS,:), ...
            meso,dt,Tobs);

        for c=1:nCond
            f=Rb(c).FPT_TS;
            rmstBoot(b,c)=mean(min(f,Tobs));
            pBoot(b,c)=mean(f<=Tobs);

            rc=Rb(c).routeCode;
            for rr=1:nRoute
                routeBoot(b,c,rr)=mean(rc==rr);
            end

            cdfBoot(b,:,c)=arrayfun(@(tt) mean(f<=tt),tCDF).';
        end

        jointDelta(b)=routeBoot(b,4,4)-routeBoot(b,1,4);

        if mod(b,max(1,round(nBoot/10)))==0
            fprintf('  two-source bootstrap %d / %d\n',b,nBoot);
        end
    end

    BOOT.RMSTCI=zeros(nCond,2);
    BOOT.PcrossCI=zeros(nCond,2);
    BOOT.routeCI=zeros(nCond,nRoute,2);
    BOOT.cdfCI=zeros(nT,nCond,2);

    for c=1:nCond
        BOOT.RMSTCI(c,:)=quantileLocal(rmstBoot(:,c),[alpha/2 1-alpha/2]);
        BOOT.PcrossCI(c,:)=quantileLocal(pBoot(:,c),[alpha/2 1-alpha/2]);

        for rr=1:nRoute
            q=quantileLocal(routeBoot(:,c,rr),[alpha/2 1-alpha/2]);
            BOOT.routeCI(c,rr,1)=q(1);
            BOOT.routeCI(c,rr,2)=q(2);
        end

        for it=1:nT
            q=quantileLocal(cdfBoot(:,it,c),[alpha/2 1-alpha/2]);
            BOOT.cdfCI(it,c,1)=q(1);
            BOOT.cdfCI(it,c,2)=q(2);
        end
    end

    BOOT.rmstBoot=rmstBoot;
    BOOT.pBoot=pBoot;
    BOOT.routeBoot=routeBoot;
    BOOT.jointDeltaGF_CU=jointDelta;
    BOOT.nPairsPerBootstrap=nPairs;
    BOOT.method='independent two-source empirical-bank bootstrap';
end

