%% Fig3D_candidateFieldScreening_main_SI_v3_reordered.m
% -------------------------------------------------------------------------
% Candidate-field screening after predictor-independent Fig. 3B--C.
% v3 reorganizes the main-text and supplementary figures:
%   Main: continuous association -> top-q localization -> unique association
%         (burden and FPT shown as two subpanels under one conceptual panel).
%   SI: maps -> collinearity -> full performance -> q robustness ->
%       paired bootstrap differences -> spatial-scale sensitivity.
% It retains the v2 coordinate-shadowing fix and explicit contour grids.
%
% Scientific purpose
%   Main-text figure:
%     Provide a compact comparison of three a priori spatial descriptors:
%       P1 = c1_hat                  reaction field
%       P2 = B_D = 1 - D_hat         transport-constraint field
%       P3 = X_HB = c1_hat .* B_D    composite field
%     against the predictor-independent local burden and local FPT fields
%     already generated by Fig3BC_predictorIndependent_localBurden_FPT.m.
%
%   Supplementary figure:
%     Provide the full systematic comparison, including spatial overlays,
%     marginal and partial Spearman associations, top-q overlap,
%     enrichment, AUROC, average precision, q robustness, predictor
%     collinearity, trajectory-bootstrap confidence intervals, and paired
%     bootstrap performance differences.
%
% Important design choices
%   1) This script DOES NOT rerun the RDME/SD-RDME simulations. It loads the
%      exact same Fig. 3B--C final trajectories and therefore keeps all
%      geometry, reaction, diffusion, threshold, and window settings fixed.
%   2) The primary candidate score for each local window is the mean
%      candidate-field value within that same fixed-radius window. This
%      aligns the spatial scale of the input descriptor with the local
%      burden/FPT endpoint. Center-voxel scores are retained as a sensitivity
%      audit and exported.
%   3) The local burden target is the SSA ensemble-mean difference:
%         Delta B_k = E[B_k^SD] - E[B_k^U].
%      The local FPT target is:
%         Delta RMST_k = RMST_k^U - RMST_k^SD,
%      so larger values consistently indicate greater SD-RDME local risk.
%   4) Uncertainty is estimated by resampling complete SSA trajectories,
%      rather than treating overlapping windows as independent replicates.
%   5) This analysis is the DISCOVERY / candidate-screening stage. The
%      subsequent c1_hat spatial-validation figure should use an independent
%      trajectory ensemble or independent random seeds.
%
% Required input
%   Fig3BC_predictorIndependent_data.mat
%   generated by Fig3BC_predictorIndependent_localBurden_FPT.m
%
% Outputs
%   Fig3D_candidateFieldScreening_main.{pdf,png,tif,fig}
%   FigS_candidateFieldScreening_systematic.{pdf,png,tif,fig}
%   Fig3D_candidateFieldScreening_summary.csv
%   Fig3D_candidateFieldScreening_pairwise.csv
%   FigS_candidateFieldScreening_qRobustness.csv
%   Fig3D_candidateFieldScreening_data.mat
% -------------------------------------------------------------------------

clear; close all; clc;
clear functions;

%% --------------------------- Configuration ------------------------------
RUN_MODE = 'final';              % 'smoke' | 'pilot' | 'final'
DATA_FILE = 'Fig3BC_predictorIndependent_data.mat';
PREDICTOR_SCALE = 'window_mean'; % 'window_mean' (primary) | 'center'
USE_PARALLEL = true;
AUTO_START_POOL = true;
N_WORKERS = 8;
SAVE_FIG = true;
SAVE_DATA = true;

qMain = 0.85;
qList = 0.75:0.025:0.95;
alphaCI = 0.05;

switch lower(RUN_MODE)
    case 'smoke'
        nBoot = 100;
    case 'pilot'
        nBoot = 500;
    case 'final'
        nBoot = 1000;
    otherwise
        error('Unknown RUN_MODE: %s',RUN_MODE);
end

seedBase = 20260725;
outMain = 'Fig3D_candidateFieldScreening_main_reordered';
outSI   = 'FigS_candidateFieldScreening_systematic_reordered';
outData = 'Fig3D_candidateFieldScreening_data_reordered.mat';

%% --------------------------- Figure style -------------------------------
set(groot,'defaultFigureColor','w');
set(groot,'defaultAxesFontName','Arial');
set(groot,'defaultTextFontName','Arial');
set(groot,'defaultAxesFontSize',7);
set(groot,'defaultTextFontSize',7);
set(groot,'defaultAxesLineWidth',0.70);
set(groot,'defaultLineLineWidth',1.05);
set(groot,'defaultAxesTickDir','out');
set(groot,'defaultAxesBox','on');
set(groot,'defaultLegendInterpreter','latex');
set(groot,'defaultAxesTickLabelInterpreter','tex');

colPred = [0.88 0.36 0.10;   % c1_hat: vermillion
           0.10 0.38 0.70;   % B_D: blue
           0.48 0.24 0.62];  % X_HB: purple
colBurden = [0.12 0.12 0.12];
colFPT    = [0.00 0.53 0.53];
colText   = [0.08 0.08 0.08];

predNames  = {'c1hat','BD','XHB'};
predLabels = {'$\widehat c_1$','$B_D$','$X_{\rm HB}$'};
endpointNames  = {'burden','FPT'};
endpointLabels = {'Local burden','Local FPT'};

%% --------------------------- Load data ----------------------------------
if ~isfile(DATA_FILE)
    error(['Required file not found: %s\nRun ', ...
        'Fig3BC_predictorIndependent_localBurden_FPT.m first.'],DATA_FILE);
end
D = load(DATA_FILE);

required = {'meta','x','y','mask','c1_sd','D_Fe2_sd', ...
    'windowDensitySD','windowDensityUNI','FPT_SD','FPT_UNI'};
for i = 1:numel(required)
    if ~isfield(D,required{i})
        error('Input MAT file is missing required variable: %s',required{i});
    end
end

xCoord = D.x(:).';
yCoord = D.y(:).';
mask = logical(D.mask);
K = nnz(mask);

% Coordinate audit.  The saved geometry uses meshgrid(xCoord,yCoord), so
% mask must have numel(yCoord) rows and numel(xCoord) columns.
[nMaskRows,nMaskCols] = size(mask);
if numel(xCoord) ~= nMaskCols || numel(yCoord) ~= nMaskRows
    error(['Coordinate/mask size mismatch: mask is %d-by-%d, ', ...
        'numel(xCoord)=%d and numel(yCoord)=%d.'], ...
        nMaskRows,nMaskCols,numel(xCoord),numel(yCoord));
end
[Xplot,Yplot] = meshgrid(xCoord,yCoord);

if isfield(D.meta,'Tobs')
    Tobs = D.meta.Tobs;
else
    Tobs = 60;
end
if isfield(D.meta,'windowRadius')
    windowRadius = D.meta.windowRadius;
else
    windowRadius = 0.10;
end

windowDensitySD  = D.windowDensitySD;
windowDensityUNI = D.windowDensityUNI;
FPT_SD  = D.FPT_SD;
FPT_UNI = D.FPT_UNI;

assert(size(windowDensitySD,2)==K && size(windowDensityUNI,2)==K, ...
    'Window-burden matrices must have K columns.');
assert(size(FPT_SD,2)==K && size(FPT_UNI,2)==K, ...
    'FPT matrices must have K columns.');

fprintf('============================================================\n');
fprintf('Candidate-field screening (%s)\n',upper(RUN_MODE));
fprintf('Input data                    = %s\n',DATA_FILE);
fprintf('K local windows               = %d\n',K);
fprintf('Tobs                          = %.1f min\n',Tobs);
fprintf('Window radius                 = %.3f\n',windowRadius);
fprintf('Burden trajectories: SD / U   = %d / %d\n', ...
    size(windowDensitySD,1),size(windowDensityUNI,1));
fprintf('FPT trajectories: SD / U      = %d / %d\n', ...
    size(FPT_SD,1),size(FPT_UNI,1));
fprintf('Bootstrap replicates          = %d\n',nBoot);
fprintf('============================================================\n');

%% ---------------------- Reconstruct local windows -----------------------
coordX = Xplot(mask);
coordY = Yplot(mask);
win = buildCircularWindowsSparse(coordX,coordY,windowRadius);

fprintf('Window size range             = [%d, %d]\n', ...
    min(win.size),max(win.size));
fprintf('Median window size            = %.1f\n',median(win.size));

%% ---------------------- Build three candidate fields --------------------
c1Center = normalizeVector(D.c1_sd(mask));
DhatCenter = normalizeVector(D.D_Fe2_sd(mask));
BDCenter = 1-DhatCenter;
XHBCenter = normalizeVector(c1Center.*BDCenter);
predCenter = [c1Center,BDCenter,XHBCenter];

% Window-scale candidate scores: same support as local burden/FPT endpoints.
predWindow = zeros(K,3);
for p = 1:3
    predWindow(:,p) = (win.W*predCenter(:,p))./win.size;
    predWindow(:,p) = normalizeVector(predWindow(:,p));
end

switch lower(PREDICTOR_SCALE)
    case 'window_mean'
        predVec = predWindow;
    case 'center'
        predVec = predCenter;
    otherwise
        error('Unknown PREDICTOR_SCALE: %s',PREDICTOR_SCALE);
end

predMap = NaN([size(mask),3]);
for p = 1:3
    tmp = NaN(size(mask));
    tmp(mask) = predVec(:,p);
    predMap(:,:,p) = tmp;
end

%% ---------------------- Predictor-independent targets -------------------
targetBurden = mean(windowDensitySD,1).' - mean(windowDensityUNI,1).';

FPT_SD_cens  = min(FPT_SD,Tobs);
FPT_UNI_cens = min(FPT_UNI,Tobs);
targetFPT = mean(FPT_UNI_cens,1).' - mean(FPT_SD_cens,1).';

targets = [targetBurden,targetFPT];
nPred = 3;
nEnd  = 2;
topFracMain = 1-qMain;
nTopMain = max(1,ceil(topFracMain*K));

obsTop = false(K,nEnd);
for e = 1:nEnd
    obsTop(:,e) = topNMask(targets(:,e),nTopMain);
end

%% ---------------------- Point-estimate metrics --------------------------
prep = preparePredictors(predVec,nTopMain);

point = initializeMetricStruct(nPred,nEnd);
for e = 1:nEnd
    point = fillMetrics(point,predVec,prep,targets(:,e),obsTop(:,e),e);
end

% Center-voxel sensitivity audit.
prepCenter = preparePredictors(predCenter,nTopMain);
pointCenter = initializeMetricStruct(nPred,nEnd);
for e = 1:nEnd
    pointCenter = fillMetrics(pointCenter,predCenter,prepCenter, ...
        targets(:,e),obsTop(:,e),e);
end

% Predictor-to-predictor rank correlation.
predictorRho = eye(nPred);
for i = 1:nPred
    for j = i+1:nPred
        predictorRho(i,j) = pearsonLocal(prep.rank(:,i),prep.rank(:,j));
        predictorRho(j,i) = predictorRho(i,j);
    end
end

%% ---------------------- Trajectory-bootstrap targets --------------------
usePar = configureParallel(USE_PARALLEL,AUTO_START_POOL,N_WORKERS);

fprintf('\nBootstrapping burden target fields...\n');
bootBurden = bootstrapMeanDifferenceFields( ...
    windowDensitySD,windowDensityUNI,nBoot,seedBase+1000,usePar);

fprintf('Bootstrapping FPT target fields...\n');
bootFPT = bootstrapMeanDifferenceFields( ...
    FPT_UNI_cens,FPT_SD_cens,nBoot,seedBase+2000,usePar);

%% ---------------------- Bootstrap metric uncertainty --------------------
boot.rho     = zeros(nBoot,nPred,nEnd);
boot.partial = zeros(nBoot,nPred,nEnd);
boot.J       = zeros(nBoot,nPred,nEnd);
boot.E       = zeros(nBoot,nPred,nEnd);
boot.AUC     = zeros(nBoot,nPred,nEnd);
boot.AP      = zeros(nBoot,nPred,nEnd);

for b = 1:nBoot
    bTargets = [bootBurden(b,:).',bootFPT(b,:).'];
    for e = 1:nEnd
        targetVec = bTargets(:,e);
        targetTop = topNMask(targetVec,nTopMain);
        rY = tiedRankLocal(targetVec);
        for p = 1:nPred
            boot.rho(b,p,e) = pearsonLocal(prep.rank(:,p),rY);
            boot.partial(b,p,e) = applyPartial(prep.partial(p),rY);
            [boot.J(b,p,e),boot.E(b,p,e)] = ...
                overlapMetricsEqualSize(prep.topMain(:,p),targetTop);
            [boot.AUC(b,p,e),boot.AP(b,p,e)] = ...
                binaryDiscrimination(predVec(:,p),targetTop);
        end
    end
end

point = attachBootstrapCI(point,boot,alphaCI);

%% ---------------------- Pairwise paired-bootstrap differences -----------
% Positive values favor c1_hat over the comparison predictor.
comparisons = {'c1hat-BD','c1hat-XHB'};
compareIdx = [1 2;1 3];
metricKeys = {'rho','partial','J','AUC','AP'};
metricLabels = {'Spearman','PartialSpearman','Jaccard','AUROC','AP'};

rows = {};
for e = 1:nEnd
    for m = 1:numel(metricKeys)
        key = metricKeys{m};
        B = boot.(key);
        for c = 1:size(compareIdx,1)
            a = compareIdx(c,1);
            z = compareIdx(c,2);
            dBoot = squeeze(B(:,a,e)-B(:,z,e));
            ci = percentileCI(dBoot,alphaCI);
            dPoint = point.(key)(a,e)-point.(key)(z,e);
            rows(end+1,:) = {endpointNames{e},metricLabels{m}, ...
                comparisons{c},dPoint,ci(1),ci(2),mean(dBoot>0)}; %#ok<AGROW>
        end
    end
end
pairwiseTable = cell2table(rows,'VariableNames', ...
    {'Endpoint','Metric','Comparison','Difference','CI_L','CI_U','ProbPositive'});

%% ---------------------- q robustness -----------------------------------
Jq = zeros(numel(qList),nPred,nEnd);
Eq = zeros(numel(qList),nPred,nEnd);
for iq = 1:numel(qList)
    nTop = max(1,ceil((1-qList(iq))*K));
    for e = 1:nEnd
        yTop = topNMask(targets(:,e),nTop);
        for p = 1:nPred
            pTop = topNMask(predVec(:,p),nTop);
            [Jq(iq,p,e),Eq(iq,p,e)] = overlapMetricsEqualSize(pTop,yTop);
        end
    end
end

%% ---------------------- Summary tables ---------------------------------
summaryRows = {};
for e = 1:nEnd
    for p = 1:nPred
        summaryRows(end+1,:) = {endpointNames{e},predNames{p}, ...
            point.rho(p,e),point.rhoCI_L(p,e),point.rhoCI_U(p,e), ...
            point.partial(p,e),point.partialCI_L(p,e),point.partialCI_U(p,e), ...
            point.J(p,e),point.JCI_L(p,e),point.JCI_U(p,e), ...
            point.E(p,e),point.ECI_L(p,e),point.ECI_U(p,e), ...
            point.AUC(p,e),point.AUCCI_L(p,e),point.AUCCI_U(p,e), ...
            point.AP(p,e),point.APCI_L(p,e),point.APCI_U(p,e)}; %#ok<AGROW>
    end
end
summaryTable = cell2table(summaryRows,'VariableNames', ...
    {'Endpoint','Predictor', ...
     'Spearman','Spearman_CI_L','Spearman_CI_U', ...
     'PartialSpearman','Partial_CI_L','Partial_CI_U', ...
     'Jaccard','Jaccard_CI_L','Jaccard_CI_U', ...
     'Enrichment','Enrichment_CI_L','Enrichment_CI_U', ...
     'AUROC','AUROC_CI_L','AUROC_CI_U', ...
     'AveragePrecision','AP_CI_L','AP_CI_U'});

scaleRows = {};
for e = 1:nEnd
    for p = 1:nPred
        scaleRows(end+1,:) = {endpointNames{e},predNames{p}, ...
            point.rho(p,e),pointCenter.rho(p,e), ...
            point.J(p,e),pointCenter.J(p,e), ...
            point.AUC(p,e),pointCenter.AUC(p,e)}; %#ok<AGROW>
    end
end
scaleSensitivityTable = cell2table(scaleRows,'VariableNames', ...
    {'Endpoint','Predictor','WindowMean_Rho','Center_Rho', ...
     'WindowMean_Jaccard','Center_Jaccard', ...
     'WindowMean_AUROC','Center_AUROC'});

qRows = {};
for iq = 1:numel(qList)
    for e = 1:nEnd
        for p = 1:nPred
            qRows(end+1,:) = {qList(iq),endpointNames{e},predNames{p}, ...
                Jq(iq,p,e),Eq(iq,p,e)}; %#ok<AGROW>
        end
    end
end
qTable = cell2table(qRows,'VariableNames', ...
    {'Quantile','Endpoint','Predictor','Jaccard','Enrichment'});

%% ---------------------- Console summary ---------------------------------
fprintf('\n================ Candidate screening summary ================\n');
fprintf('Primary score scale: %s\n',PREDICTOR_SCALE);
for e = 1:nEnd
    fprintf('\nEndpoint: %s\n',endpointLabels{e});
    fprintf('Predictor      rho [95%% CI]      partial rho       Jaccard       enrich       AUROC        AP\n');
    for p = 1:nPred
        fprintf('%-8s  %6.3f [%6.3f,%6.3f]   %6.3f       %6.3f       %5.2f       %6.3f      %6.3f\n', ...
            predNames{p},point.rho(p,e),point.rhoCI_L(p,e),point.rhoCI_U(p,e), ...
            point.partial(p,e),point.J(p,e),point.E(p,e), ...
            point.AUC(p,e),point.AP(p,e));
    end
end
fprintf('\nPredictor rank-correlation matrix [c1hat, BD, XHB]:\n');
disp(predictorRho);

for e = 1:nEnd
    [~,iRho] = max(point.rho(:,e));
    [~,iJ]   = max(point.J(:,e));
    [~,iAUC] = max(point.AUC(:,e));
    fprintf('%s winners: rho=%s, Jaccard=%s, AUROC=%s\n', ...
        endpointLabels{e},predNames{iRho},predNames{iJ},predNames{iAUC});
end
fprintf('==============================================================\n');

%% ========================================================================
% MAIN-TEXT FIGURE
% D: marginal continuous association
% E: top-15% localization
% F: unique association, shown for burden and FPT as two coordinated subplots
% ========================================================================

figMain = figure('Units','centimeters','Position',[1.0 2.0 19.0 5.5], ...
    'Color','w');
tlMain = tiledlayout(figMain,1,4,'TileSpacing','compact','Padding','compact');

% D. Continuous marginal spatial association.
axD = nexttile(tlMain,1); hold(axD,'on');
plotMetricByEndpoint(axD,point.rho,point.rhoCI_L,point.rhoCI_U, ...
    colPred,colBurden,colFPT,'Spearman association',[0.80 1.01],0);
text(axD,0.02,0.98,'D','Units','normalized','FontSize',12, ...
    'FontWeight','bold','VerticalAlignment','top','Color',colText);
ylabel(axD,'Spearman $\rho_s$','Interpreter','latex');
title(axD,'Continuous spatial association', ...
    'FontSize',8.3,'FontWeight','normal');

% E. Top-q spatial localization.
axE = nexttile(tlMain,2); hold(axE,'on');
chanceJ = topFracMain/(2-topFracMain);
plotMetricByEndpoint(axE,point.J,point.JCI_L,point.JCI_U, ...
    colPred,colBurden,colFPT,'Top-15% overlap',[0 1],chanceJ);
text(axE,0.02,0.98,'E','Units','normalized','FontSize',12, ...
    'FontWeight','bold','VerticalAlignment','top','Color',colText);
ylabel(axE,'Jaccard overlap');
title(axE,'Top-15% spatial localization', ...
    'FontSize',8.3,'FontWeight','normal');
text(axE,0.98,0.055,sprintf('random = %.2f',chanceJ), ...
    'Units','normalized','HorizontalAlignment','right', ...
    'FontSize',5.8,'Color',[0.42 0.42 0.42]);

% F1. Marginal-versus-partial association for local burden.
axF1 = nexttile(tlMain,3); hold(axF1,'on');
plotMarginalPartialMain(axF1,point,1,colPred,false);
text(axF1,0.02,0.98,'F','Units','normalized','FontSize',12, ...
    'FontWeight','bold','VerticalAlignment','top','Color',colText);
ylabel(axF1,'Spearman $\rho_s$','Interpreter','latex');
title(axF1,'Unique association: local burden', ...
    'FontSize',8.3,'FontWeight','normal');

% F2. Marginal-versus-partial association for local FPT.
axF2 = nexttile(tlMain,4); hold(axF2,'on');
plotMarginalPartialMain(axF2,point,2,colPred,true);
ylabel(axF2,'Spearman $\rho_s$','Interpreter','latex');
title(axF2,'Unique association: local FPT', ...
    'FontSize',8.3,'FontWeight','normal');

% Endpoint legend for D-E.  Filled circle = burden; open square = FPT.
hBurden = plot(axE,NaN,NaN,'o','Color',[0.18 0.18 0.18], ...
    'MarkerFaceColor',[0.18 0.18 0.18],'MarkerSize',4.2);
hFPT = plot(axE,NaN,NaN,'s','Color',[0.18 0.18 0.18], ...
    'MarkerFaceColor','w','MarkerSize',4.2);
legend(axE,[hBurden hFPT],{'local burden','local FPT'}, ...
    'Box','off','Location','southwest','FontSize',5.7);

if SAVE_FIG
    exportgraphics(figMain,[outMain '.pdf'],'ContentType','vector');
    exportgraphics(figMain,[outMain '.png'],'Resolution',600);
    exportgraphics(figMain,[outMain '.tif'],'Resolution',600);
    savefig(figMain,[outMain '.fig']);
end

%% ========================================================================
% SUPPLEMENTARY FIGURE
% A-C: candidate maps and spatial overlays
% D: predictor collinearity
% E: full top-q and threshold-free performance
% F: q robustness
% G: paired bootstrap differences favoring c1hat
% H: center-versus-window-mean scale sensitivity
% ========================================================================

% Prepare paired-difference matrix for SI-G.
siMetricKeys   = {'rho','J','AUC','AP'};
siMetricLabels = {'rho','J','AUROC','AP'};
pairDiffMat = zeros(2*numel(siMetricKeys),2);
pairSigMat  = false(size(pairDiffMat));
pairCIL = zeros(size(pairDiffMat));
pairCIU = zeros(size(pairDiffMat));
pairRowLabels = cell(2*numel(siMetricKeys),1);

rr = 0;
for e = 1:nEnd
    endpointPrefix = upper(endpointNames{e}(1));
    for m = 1:numel(siMetricKeys)
        rr = rr+1;
        key = siMetricKeys{m};
        pairRowLabels{rr} = sprintf('%s: %s',endpointPrefix,siMetricLabels{m});
        for c = 1:2
            a = compareIdx(c,1);
            z = compareIdx(c,2);
            dBoot = squeeze(boot.(key)(:,a,e)-boot.(key)(:,z,e));
            ci = percentileCI(dBoot,alphaCI);
            pairDiffMat(rr,c) = point.(key)(a,e)-point.(key)(z,e);
            pairCIL(rr,c) = ci(1);
            pairCIU(rr,c) = ci(2);
            pairSigMat(rr,c) = ci(1)>0 || ci(2)<0;
        end
    end
end

% Prepare center-minus-window performance differences for SI-H.
scaleDeltaMat = zeros(2*numel(siMetricKeys),nPred);
scaleRowLabels = pairRowLabels;
rr = 0;
for e = 1:nEnd
    for m = 1:numel(siMetricKeys)
        rr = rr+1;
        key = siMetricKeys{m};
        scaleDeltaMat(rr,:) = ...
            (pointCenter.(key)(:,e)-point.(key)(:,e)).';
    end
end

figSI = figure('Units','centimeters','Position',[1.0 1.0 19.0 14.0], ...
    'Color','w');
tlSI = tiledlayout(figSI,2,4,'TileSpacing','compact','Padding','compact');

% A-C. Candidate maps with candidate and observed top-q contours.
for p = 1:3
    ax = nexttile(tlSI,p); hold(ax,'on');
    h = imagesc(ax,xCoord,yCoord,predMap(:,:,p));
    set(ax,'YDir','normal');
    set(h,'AlphaData',mask,'Interpolation','nearest');
    axis(ax,'image');
    colormap(ax,natureBlueYellow(256));
    caxis(ax,[0 1]);

    predTop = false(size(mask));
    predTop(mask) = prep.topMain(:,p);
    burdenTopMap = false(size(mask));
    burdenTopMap(mask) = obsTop(:,1);
    fptTopMap = false(size(mask));
    fptTopMap(mask) = obsTop(:,2);

    contour(ax,Xplot,Yplot,double(predTop),[0.5 0.5], ...
        'Color',[1 1 1],'LineStyle','--','LineWidth',1.15);
    contour(ax,Xplot,Yplot,double(burdenTopMap),[0.5 0.5], ...
        'Color',colBurden,'LineStyle','-','LineWidth',1.00);
    contour(ax,Xplot,Yplot,double(fptTopMap),[0.5 0.5], ...
        'Color',[0.00 0.60 0.52],'LineStyle','-','LineWidth',1.05);
    contour(ax,Xplot,Yplot,double(mask),[0.5 0.5], ...
        'Color',[0.28 0.28 0.28],'LineWidth',0.50);

    title(ax,predLabels{p},'Interpreter','latex', ...
        'FontSize',8.5,'FontWeight','normal');
    xlabel(ax,'x'); ylabel(ax,'y');
    text(ax,0.02,0.98,char('A'+p-1),'Units','normalized', ...
        'FontSize',11.5,'FontWeight','bold', ...
        'VerticalAlignment','top','Color',colText);

    txt = {sprintf('$J_B=%.2f,\\ J_F=%.2f$', ...
               point.J(p,1),point.J(p,2)), ...
           sprintf('$E_B=%.1f\\times,\\ E_F=%.1f\\times$', ...
               point.E(p,1),point.E(p,2))};
    text(ax,0.04,0.07,txt,'Units','normalized','Interpreter','latex', ...
