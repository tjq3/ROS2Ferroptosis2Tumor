function usePar = configureParallel(requested,autoStart,nWorkers)
    usePar = false;
    if ~requested, return; end
    try
        if ~license('test','Distrib_Computing_Toolbox')
            warning('Parallel Computing Toolbox unavailable; using serial loops.');
            return;
        end
        pool = gcp('nocreate');
        if isempty(pool) && autoStart
            pool = parpool('local',nWorkers);
        end
        usePar = ~isempty(pool);
    catch ME
        warning('Parallel setup failed (%s); using serial loops.',ME.message);
        usePar = false;
    end
end

function win = buildCircularWindowsSparse(coordX,coordY,radius)
    K = numel(coordX);
    I = cell(K,1); J = cell(K,1);
    for k = 1:K
        idx = find((coordX-coordX(k)).^2 + ...
                   (coordY-coordY(k)).^2 <= radius^2+1e-14);
        I{k} = repmat(k,numel(idx),1);
        J{k} = idx(:);
    end
    I = vertcat(I{:}); J = vertcat(J{:});
    W = sparse(I,J,1,K,K);
    win.W = W;
    win.size = full(sum(W,2));
end

function v = normalizeVector(v)
    v = v(:);
    lo = min(v);
    hi = max(v);
    v = (v-lo)/(hi-lo+eps);
end

function prep = preparePredictors(predVec,nTop)
    [K,nPred] = size(predVec);
    prep.rank = zeros(K,nPred);
    prep.topMain = false(K,nPred);
    nTop = min(max(round(nTop),1),K);
    for p = 1:nPred
        prep.rank(:,p) = tiedRankLocal(predVec(:,p));
        prep.topMain(:,p) = topNMask(predVec(:,p),nTop);
    end

    % Unique associations:
    % c1 controlling BD; BD controlling c1; XHB controlling c1 and BD.
    controlSets = {2,1,[1 2]};
    prep.partial = repmat(struct('X',[],'rx',[]),nPred,1);
    for p = 1:nPred
        controls = controlSets{p};
        X = ones(K,1);
        for c = controls
            X = [X,tiedRankLocal(predVec(:,c))]; %#ok<AGROW>
        end
        rx = prep.rank(:,p)-X*(pinv(X)*prep.rank(:,p));
        prep.partial(p).X = X;
        prep.partial(p).rx = rx;
    end
end

function point = initializeMetricStruct(nPred,nEnd)
    fields = {'rho','partial','J','E','AUC','AP', ...
        'rhoCI_L','rhoCI_U','partialCI_L','partialCI_U', ...
        'JCI_L','JCI_U','ECI_L','ECI_U', ...
        'AUCCI_L','AUCCI_U','APCI_L','APCI_U'};
    for i = 1:numel(fields)
        point.(fields{i}) = NaN(nPred,nEnd);
    end
end

function point = fillMetrics(point,predVec,prep,target,targetTop,e)
    rY = tiedRankLocal(target);
    for p = 1:size(predVec,2)
        point.rho(p,e) = pearsonLocal(prep.rank(:,p),rY);
        point.partial(p,e) = applyPartial(prep.partial(p),rY);
        [point.J(p,e),point.E(p,e)] = ...
            overlapMetricsEqualSize(prep.topMain(:,p),targetTop);
        [point.AUC(p,e),point.AP(p,e)] = ...
            binaryDiscrimination(predVec(:,p),targetTop);
    end
end

function rho = applyPartial(prep,yRank)
    ry = yRank-prep.X*(pinv(prep.X)*yRank);
    rho = pearsonLocal(prep.rx,ry);
end

function point = attachBootstrapCI(point,boot,alpha)
    keys = {'rho','partial','J','E','AUC','AP'};
    for k = 1:numel(keys)
        key = keys{k};
        B = boot.(key);
        lowName = [key 'CI_L'];
        upName  = [key 'CI_U'];
        for p = 1:size(B,2)
            for e = 1:size(B,3)
                ci = percentileCI(squeeze(B(:,p,e)),alpha);
                point.(lowName)(p,e) = ci(1);
                point.(upName)(p,e) = ci(2);
            end
        end
    end
end

function bootFields = bootstrapMeanDifferenceFields(A,B,nBoot,seed,usePar)
    % Returns mean(A*) - mean(B*) for each bootstrap replicate.
    nA = size(A,1);
    nB = size(B,1);
    K = size(A,2);
    bootFields = zeros(nBoot,K);

    if usePar
        parfor b = 1:nBoot
            rng(seed+b,'twister');
            iA = randi(nA,nA,1);
            iB = randi(nB,nB,1);
            bootFields(b,:) = mean(A(iA,:),1)-mean(B(iB,:),1);
        end
    else
        for b = 1:nBoot
            rng(seed+b,'twister');
            iA = randi(nA,nA,1);
            iB = randi(nB,nB,1);
            bootFields(b,:) = mean(A(iA,:),1)-mean(B(iB,:),1);
            if mod(b,max(1,round(nBoot/10)))==0
                fprintf('  finished %d / %d bootstrap fields\n',b,nBoot);
            end
        end
    end
end

function m = topNMask(v,nTop)
    v = v(:);
    K = numel(v);
    nTop = min(max(round(nTop),1),K);
    [~,ord] = sortrows([-v,(1:K).'],[1 2]);
    m = false(K,1);
    m(ord(1:nTop)) = true;
end

function [J,E] = overlapMetricsEqualSize(a,b)
    a = logical(a(:)); b = logical(b(:));
    inter = nnz(a & b);
    uni = nnz(a | b);
    J = inter/max(uni,1);
    expected = nnz(a)*nnz(b)/numel(a);
    E = inter/max(expected,eps);
end

function [AUC,AP] = binaryDiscrimination(score,label)
    score = score(:);
    label = logical(label(:));
    nPos = nnz(label);
    nNeg = numel(label)-nPos;
    if nPos==0 || nNeg==0
        AUC = NaN; AP = NaN; return;
    end

    r = tiedRankLocal(score);
    AUC = (sum(r(label))-nPos*(nPos+1)/2)/(nPos*nNeg);

    [~,ord] = sortrows([-score,(1:numel(score)).'],[1 2]);
    y = label(ord);
    tp = cumsum(y);
    precision = tp./(1:numel(y)).';
    AP = sum(precision(y))/nPos;
end

function r = tiedRankLocal(x)
    x = x(:);
    [xs,ord] = sort(x);
    r = zeros(size(x));
    i = 1; n = numel(x);
    while i<=n
        j = i;
        while j<n && xs(j+1)==xs(i)
            j = j+1;
        end
        r(ord(i:j)) = (i+j)/2;
        i = j+1;
    end
end

function r = pearsonLocal(x,y)
    x = x(:)-mean(x(:));
    y = y(:)-mean(y(:));
    r = sum(x.*y)/sqrt(max(sum(x.^2)*sum(y.^2),eps));
end

function ci = percentileCI(v,alpha)
    ci = [quantileLocal(v,alpha/2),quantileLocal(v,1-alpha/2)];
end

function q = quantileLocal(x,p)
    x = sort(x(:));
    n = numel(x);
    if n==0, q = NaN; return; end
    p = min(max(p,0),1);
    pos = 1+p*(n-1);
    lo = floor(pos); hi = ceil(pos);
    if lo==hi
        q = x(lo);
    else
        q = x(lo)+(pos-lo)*(x(hi)-x(lo));
    end
end

