%% =========================================================================
% EXACT EVENT-LOG REPLAY
% =========================================================================
function D = replayEventLogMechanism( ...
    O,initialChiMap,initialMask,chiLow,chiHigh,targetNV)

L = O.cfg.L;
nSite = L^3;
ctr = [(L+1)/2 (L+1)/2 (L+1)/2];

state = zeros(nSite,1,'uint8');
initialIdx = find(initialMask(:));
state(initialIdx) = uint8(1);

mark = nan(nSite,1);
A = double(initialChiMap(:));
mark(initialIdx) = A(initialIdx);

tol = 1e-9*max(1,abs(chiHigh));

EL = O.event_log;
assert(~isempty(EL),'Event log is empty.');
eventTime = double(EL.time_h);
eventType = double(EL.eventType);
eventSite = double(EL.site);
eventTarget = double(EL.target);

tRec = double(O.t_h(:));
nRec = numel(tRec);
nEvt = height(EL);

K = zeros(3,3,3);
K(2,2,1)=1; K(2,2,3)=1;
K(2,1,2)=1; K(2,3,2)=1;
K(1,2,2)=1; K(3,2,2)=1;

lowEmptyEdges = zeros(nRec,1);
lowEmptyPerLow = nan(nRec,1);
lowHighInterface = zeros(nRec,1);
lowFracViable = nan(nRec,1);

cumLowBirth = zeros(nRec,1);
cumHighBirth = zeros(nRec,1);
cumLowFerro = zeros(nRec,1);
cumHighFerro = zeros(nRec,1);
cumLowClear = zeros(nRec,1);
cumHighClear = zeros(nRec,1);
cumHighClearAccessible = zeros(nRec,1);
cumHighClearLowNbr = zeros(nRec,1);

nLowBirth=0; nHighBirth=0;
nLowFerro=0; nHighFerro=0;
nLowClear=0; nHighClear=0;

nHighClearAccessible=0;
sumLowNbrAtHighClear=0;

% Exact event-time integral of low-V <-> empty neighbour edges.
currentLE = totalLowEmptyEdgesExact(state,mark,chiLow,tol,L);
integratedLE = 0;
tPrevEvent = 0;

matchedRecorded=false;
matchedTime=NaN;
matchedCavity=NaN;

timeLow90=NaN;

ev=1;
prevNV=nnz(state==1);

for ir=1:nRec
    tr=tRec(ir);

    while ev<=nEvt && eventTime(ev)<=tr+1e-12

        te = min(eventTime(ev),O.cfg.Tend_h);
        if te>tPrevEvent
            integratedLE = integratedLE + currentLE*(te-tPrevEvent);
            tPrevEvent = te;
        end

        typ=eventType(ev);
        s=eventSite(ev);
        tg=eventTarget(ev);

        if typ==1
            oldLocalLE = localLowEmptyContributionExact( ...
                tg,state,mark,chiLow,tol,L);
            % Birth: mark is inherited exactly from the parent.
            assert(s>=1 && s<=nSite && tg>=1 && tg<=nSite);
            assert(state(s)==1,'Replay birth parent is not viable.');
            assert(state(tg)==0,'Replay birth target is not empty.');
            assert(isfinite(mark(s)),'Replay birth parent has no mark.');

            state(tg)=uint8(1);
            mark(tg)=mark(s);

            newLocalLE = localLowEmptyContributionExact( ...
                tg,state,mark,chiLow,tol,L);
            currentLE = currentLE + (newLocalLE-oldLocalLE);

            if abs(mark(s)-chiLow)<=tol
                nLowBirth=nLowBirth+1;
            elseif abs(mark(s)-chiHigh)<=tol
                nHighBirth=nHighBirth+1;
            else
                error('Unexpected cell mark at birth.');
            end

        elseif typ==2
            % Ferroptotic commitment V -> F.
            oldLocalLE = localLowEmptyContributionExact( ...
                s,state,mark,chiLow,tol,L);
            assert(s>=1 && s<=nSite);
            assert(state(s)==1,'Replay ferro site is not viable.');
            assert(isfinite(mark(s)),'Replay ferro site has no mark.');

            if abs(mark(s)-chiLow)<=tol
                nLowFerro=nLowFerro+1;
            elseif abs(mark(s)-chiHigh)<=tol
                nHighFerro=nHighFerro+1;
            else
                error('Unexpected cell mark at ferroptosis.');
            end

            state(s)=uint8(2);
            newLocalLE = localLowEmptyContributionExact( ...
                s,state,mark,chiLow,tol,L);
            currentLE = currentLE + (newLocalLE-oldLocalLE);
            % IMPORTANT: retain the mark externally while in F so that a
            % later clearance event can be assigned to low/high lineage.

        elseif typ==3
            % Clearance F -> empty.
            oldLocalLE = localLowEmptyContributionExact( ...
                s,state,mark,chiLow,tol,L);
            assert(s>=1 && s<=nSite);
            assert(state(s)==2,'Replay clearance site is not F.');
            assert(isfinite(mark(s)),'Replay F site has no retained mark.');

            if abs(mark(s)-chiHigh)<=tol
                nHighClear=nHighClear+1;

                nbr=neighbourIndicesLocal(s,L);
                isLowNbr = state(nbr)==1 & ...
                    abs(mark(nbr)-chiLow)<=tol;
                nLowNbr = nnz(isLowNbr);

                sumLowNbrAtHighClear = sumLowNbrAtHighClear+nLowNbr;
                if nLowNbr>0
                    nHighClearAccessible=nHighClearAccessible+1;
                end

            elseif abs(mark(s)-chiLow)<=tol
                nLowClear=nLowClear+1;
            else
                error('Unexpected cell mark at clearance.');
            end

            state(s)=uint8(0);
            mark(s)=NaN;

            newLocalLE = localLowEmptyContributionExact( ...
                s,state,mark,chiLow,tol,L);
            currentLE = currentLE + (newLocalLE-oldLocalLE);

        else
            error('Unknown event type in log.');
        end

        newNV=nnz(state==1);

        % First DOWNWARD crossing of the matched viable-burden target.
        if ~matchedRecorded && typ==2 && prevNV>targetNV && newNV<=targetNV
            matchedRecorded=true;
            matchedTime=eventTime(ev);
            matchedCavity=cavityFractionFromState(state,L,ctr);
        end

        prevNV=newNV;
        ev=ev+1;
    end

    % Record replay-derived spatial quantities.
    S3=reshape(state,[L L L]);
    M3=reshape(mark,[L L L]);

    lowV = (S3==1) & isfinite(M3) & abs(M3-chiLow)<=tol;
    highV = (S3==1) & isfinite(M3) & abs(M3-chiHigh)<=tol;
    empty = (S3==0);

    nLow=nnz(lowV);
    nHigh=nnz(highV);
    nV=nLow+nHigh;

    nEmptyNbr = convn(double(empty),K,'same');
    lowEmptyEdges(ir)=sum(nEmptyNbr(lowV));

    if nLow>0
        lowEmptyPerLow(ir)=lowEmptyEdges(ir)/nLow;
    end

    nHighNbr = convn(double(highV),K,'same');
    lowHighInterface(ir)=sum(nHighNbr(lowV)); % each L-H edge counted once

    if nV>0
        lowFracViable(ir)=nLow/nV;
    end

    cumLowBirth(ir)=nLowBirth;
    cumHighBirth(ir)=nHighBirth;
    cumLowFerro(ir)=nLowFerro;
    cumHighFerro(ir)=nHighFerro;
    cumLowClear(ir)=nLowClear;
    cumHighClear(ir)=nHighClear;
    cumHighClearAccessible(ir)=nHighClearAccessible;
    cumHighClearLowNbr(ir)=sumLowNbrAtHighClear;

    if ~isfinite(timeLow90) && isfinite(lowFracViable(ir)) && lowFracViable(ir)>=0.90
        timeLow90=tr;
    end
end

% Complete exact access integration from the final event to Tend.
if tPrevEvent<O.cfg.Tend_h
    integratedLE = integratedLE + currentLE*(O.cfg.Tend_h-tPrevEvent);
end

% Replay must match the solver record-grid counts exactly.
NVreplay = zeros(nRec,1);
% We can recover it from the lineages already recorded:
for ir=1:nRec
    % derive via lowFrac is insufficient at zeros, so reconstruct from event
    % accounting using the solver NV check below through a second identity:
    % initial NV + births - ferro.
    NVreplay(ir)=numel(initialIdx) + ...
        cumLowBirth(ir)+cumHighBirth(ir) - ...
        cumLowFerro(ir)-cumHighFerro(ir);
end

maxReplayNVError=max(abs(NVreplay-double(O.NV(:))));
maxReplayBirthError=max(abs( ...
    (cumLowBirth+cumHighBirth)-double(O.cumBirth(:))));

% Class identity should equal total viable count.
classNV = zeros(nRec,1);
% Exact class counts from event bookkeeping:
nLow0=nnz(abs(A(initialIdx)-chiLow)<=tol);
nHigh0=nnz(abs(A(initialIdx)-chiHigh)<=tol);

classLow = nLow0 + cumLowBirth - cumLowFerro;
classHigh = nHigh0 + cumHighBirth - cumHighFerro;
classNV = classLow+classHigh;

maxReplayClassError=max(abs(classNV-double(O.NV(:))));

if nHighClear>0
    highClearAccessibleFrac=nHighClearAccessible/nHighClear;
    highClearMeanLowNbr=sumLowNbrAtHighClear/nHighClear;
else
    highClearAccessibleFrac=NaN;
    highClearMeanLowNbr=NaN;
end

D=struct();
D.lowEmptyEdges=lowEmptyEdges;
D.lowEmptyPerLow=lowEmptyPerLow;
D.integratedLowEmptyEdgeHours=integratedLE;
D.lowHighInterface=lowHighInterface;
D.lowFracViable=lowFracViable;

D.cumLowBirth=cumLowBirth;
D.cumHighBirth=cumHighBirth;
D.cumLowFerro=cumLowFerro;
D.cumHighFerro=cumHighFerro;
D.cumLowClear=cumLowClear;
D.cumHighClear=cumHighClear;

D.cumHighClearAccessible=cumHighClearAccessible;
D.cumHighClearLowNbr=cumHighClearLowNbr;

D.highClearTotal=nHighClear;
D.highClearAccessibleFrac=highClearAccessibleFrac;
D.highClearMeanLowNbr=highClearMeanLowNbr;

D.matchedTime_h=matchedTime;
D.matchedCavity=matchedCavity;
D.timeLowFrac90_h=timeLow90;

D.maxReplayNVError=maxReplayNVError;
D.maxReplayBirthError=maxReplayBirthError;
D.maxReplayClassError=maxReplayClassError;

end

