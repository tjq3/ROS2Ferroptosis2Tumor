function total=totalLowEmptyEdgesExact(state,mark,chiLow,tol,L)
lowIdx=find(state==1 & isfinite(mark) & abs(mark-chiLow)<=tol);
total=0;
for k=1:numel(lowIdx)
    nbr=neighbourIndicesLocal(lowIdx(k),L);
    total=total+nnz(state(nbr)==0);
end
end

function c=localLowEmptyContributionExact(idx,state,mark,chiLow,tol,L)
% Number of low-V <-> empty edges incident to idx.
nbr=neighbourIndicesLocal(idx,L);
c=0;

isLowHere=state(idx)==1 && isfinite(mark(idx)) && abs(mark(idx)-chiLow)<=tol;
isEmptyHere=state(idx)==0;

for q=1:numel(nbr)
    j=nbr(q);
    isLowNbr=state(j)==1 && isfinite(mark(j)) && abs(mark(j)-chiLow)<=tol;
    isEmptyNbr=state(j)==0;
    if (isLowHere && isEmptyNbr) || (isEmptyHere && isLowNbr)
        c=c+1;
    end
end
end

function nbr=neighbourIndicesLocal(idx,L)

[i,j,k]=ind2sub([L L L],idx);
nbr=zeros(6,1);
n=0;

if i>1, n=n+1; nbr(n)=sub2ind([L L L],i-1,j,k); end
if i<L, n=n+1; nbr(n)=sub2ind([L L L],i+1,j,k); end
if j>1, n=n+1; nbr(n)=sub2ind([L L L],i,j-1,k); end
if j<L, n=n+1; nbr(n)=sub2ind([L L L],i,j+1,k); end
if k>1, n=n+1; nbr(n)=sub2ind([L L L],i,j,k-1); end
if k<L, n=n+1; nbr(n)=sub2ind([L L L],i,j,k+1); end

nbr=nbr(1:n);

end

function c=cavityFractionFromState(state,L,ctr)

occ=find(state~=0);

if isempty(occ)
    c=0;
    return;
end

[ii,jj,kk]=ind2sub([L L L],occ);

rr=sqrt((double(ii)-ctr(1)).^2 + ...
        (double(jj)-ctr(2)).^2 + ...
        (double(kk)-ctr(3)).^2);

Rmax=max(rr);

[xg,yg,zg]=ndgrid(1:L,1:L,1:L);
inside=(double(xg)-ctr(1)).^2 + ...
       (double(yg)-ctr(2)).^2 + ...
       (double(zg)-ctr(3)).^2 <= Rmax^2+1e-12;

state3=reshape(state,[L L L]);

c=nnz(inside & state3==0)/max(nnz(inside),1);

end

