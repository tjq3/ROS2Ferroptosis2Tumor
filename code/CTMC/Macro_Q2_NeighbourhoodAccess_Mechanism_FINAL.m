end

function ci=bootstrapMeanCI(x,nBoot,seed)

x=double(x(:));
x=x(isfinite(x));

if isempty(x)
    ci=[NaN NaN];
    return;
end

rng(seed,'twister');
n=numel(x);
boot=zeros(nBoot,1);

for b=1:nBoot
    ii=randi(n,n,1);
    boot(b)=mean(x(ii));
end

boot=sort(boot);
lo=max(1,round(0.025*nBoot));
hi=min(nBoot,round(0.975*nBoot));
ci=[boot(lo) boot(hi)];

end

function ci=bootstrapSlopeCI(x,y,nBoot,seed)

x=double(x(:));
y=double(y(:));
mask=isfinite(x)&isfinite(y);
x=x(mask);
y=y(mask);

if numel(x)<3
    ci=[NaN NaN];
    return;
end

rng(seed,'twister');
n=numel(x);
slopes=nan(nBoot,1);

for b=1:nBoot
    ii=randi(n,n,1);

    xb=x(ii);
    yb=y(ii);

    if numel(unique(xb))<2
        continue;
    end

    p=polyfit(xb,yb,1);
    slopes(b)=p(1);
end

slopes=sort(slopes(isfinite(slopes)));

if isempty(slopes)
    ci=[NaN NaN];
    return;
end

lo=max(1,round(0.025*numel(slopes)));
hi=min(numel(slopes),round(0.975*numel(slopes)));
ci=[slopes(lo) slopes(hi)];

end

function [r,slope,intercept]=simpleLinearAssociation(x,y)

x=double(x(:));
y=double(y(:));

mask=isfinite(x)&isfinite(y);
x=x(mask);
y=y(mask);

if numel(x)<2
    r=NaN; slope=NaN; intercept=NaN;
    return;
end

C=corrcoef(x,y);
r=C(1,2);

p=polyfit(x,y,1);
slope=p(1);
intercept=p(2);

end

