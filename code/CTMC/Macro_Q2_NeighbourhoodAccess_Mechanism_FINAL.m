function Macro_Q2_NeighbourhoodAccess_Mechanism_FINAL()
% =========================================================================
% Macro_Q2_NeighbourhoodAccess_Mechanism_FINAL
% FIX 2026-08-23: corrected nRep x nArr orientation after trapz/squeeze.
%
% NEXT STEP AFTER Macro_Q2_SpatialArrangement_PILOT:
%
% Targeted mechanism audit at the SAME frozen Q2 FINAL anchor parameter point.
% No new parameter scan is introduced here.
%
% SCIENTIFIC QUESTION
% -------------------
% The Q2 pilot showed, at identical low/high ferroptotic-susceptibility
% composition:
%
%       Dispersed ~ Random > Clustered   for integrated viable burden.
%
% This script tests the proposed neighbourhood-access mechanism:
%
%   positive clustering
%       -> fewer low-susceptibility viable cells adjacent to newly available
%          empty sites
%       -> lower low-lineage birth opportunity / lower low-lineage birth flux
%       -> lower viable tumour burden
%
% while also testing whether clustered patterns retain stronger cavity
% formation at matched viable burden.
%
% IMPORTANT
% ---------
% 1) The frozen event-driven SSA solver is NOT modified.
% 2) We rerun the exact SAME pilot seed families with store_event_log=true.
% 3) The event log is replayed outside the solver.
% 4) Because daughter_lambda_rule='inherit', cell marks can be reconstructed
%    exactly from the birth parent -> child event sequence.
% 5) The rerun is required to reproduce the original Q2 pilot AUTC and
%    initial Moran's I before any mechanistic quantity is interpreted.
%
% PRIMARY MECHANISTIC QUANTITIES
% ------------------------------
% E_LE(t)
%   Number of directed low-susceptibility viable -> empty neighbour edges.
%
% a_LE(t)
%   E_LE(t) / N_L(t):
%   accessible empty neighbours per surviving low-susceptibility viable cell.
%
% A_LE
%   Integral of E_LE(t) over time ("low-lineage accessible-edge hours").
%
% B_L(t)
%   Cumulative births generated by low-susceptibility parents.
%
% H-clearance accessibility
%   For each clearance of a high-susceptibility F cell, count how many
%   low-susceptibility viable neighbours are present at that instant.
%
% f_L(t)
%   Fraction of viable cells belonging to the low-susceptibility lineage.
%
% MATCHED-BURDEN MORPHOLOGY
% -------------------------
% The cavity fraction is additionally measured at the FIRST downward crossing
% of NV <= TARGET_NV, rather than only at a fixed clock time. This separates
% spatial fragmentation from the trivial effect of comparing very different
% viable burdens.
%
% CONDITIONS
% ----------
% Only the heterogeneous matched-composition conditions are used:
%   Dispersed / Random / Clustered.
%
% Homogeneous is not used in lineage-access calculations because it has no
% low/high cell classes.
%
% REQUIRED
% --------
% macro_sim_core_hazard_SSA_FINAL.m
% Macro_Q2_SpatialArrangement_PILOT_OUT/
%     Macro_Q2_SpatialArrangement_PILOT.mat
%
% OUTPUT
% ------
% Macro_Q2_NeighbourhoodAccess_Mechanism_FINAL_OUT/
%   Macro_Q2_NeighbourhoodAccess_Mechanism_Audit_PILOT.mat
%   Macro_Q2_NeighbourhoodAccess_Mechanism_Summary.csv
%   Macro_Q2_NeighbourhoodAccess_Mechanism_PairedEffects.csv
%   Macro_Q2_NeighbourhoodAccess_Mechanism_Audit_PILOT.png
%
% =========================================================================

clc;
close all;

%% ========================================================================
% 0. FINAL SETTINGS
% =========================================================================
% The FINAL mechanism confirmation uses the same frozen Q2 anchor definition
% and the same FINAL seed families as Macro_Q2_SpatialArrangement_FINAL.
% Event logging is passive; therefore the rerun must reproduce the FINAL
% spatial-arrangement AUTC and Moran's I exactly before mechanistic quantities
% are accepted.
TARGET_NV = 150;
N_BOOT = 10000;

% MUST match Macro_Q2_SpatialArrangement_FINAL.m
SEED_PATTERN_BASE = 1910000;
SEED_SIM_BASE     = 1920000;

% Bootstrap-only seed family can be independent.
SEED_BOOT         = 2940000;

USE_PARALLEL = true;
AUTO_START_POOL = true;

arrNames = {'Dispersed','Random','Clustered'};
nArr = numel(arrNames);

%% ========================================================================
% 1. LOAD THE COMPLETED Q2 FINAL SPATIAL TEST + FROZEN SOLVER
% =========================================================================
scriptDir = fileparts(mfilename('fullpath'));
if isempty(scriptDir), scriptDir = pwd; end

coreFile = fullfile(scriptDir,'macro_sim_core_hazard_SSA_FINAL.m');

finalCandidates = { ...
    fullfile(scriptDir,'Macro_Q2_SpatialArrangement_FINAL_OUT', ...
        'Macro_Q2_SpatialArrangement_FINAL.mat'), ...
    fullfile(scriptDir,'Macro_Q2_SpatialArrangement_FINAL.mat')};

assert(isfile(coreFile),'Missing macro_sim_core_hazard_SSA_FINAL.m.');

finalFile = '';
for k=1:numel(finalCandidates)
    if isfile(finalCandidates{k})
        finalFile = finalCandidates{k};
        break;
    end
end
assert(~isempty(finalFile), ...
    ['Cannot find Macro_Q2_SpatialArrangement_FINAL.mat. Run ', ...
     'Macro_Q2_SpatialArrangement_FINAL.m first.']);

S = load(finalFile,'Q2');
assert(isfield(S,'Q2'),'FINAL spatial MAT must contain Q2.');
Q2F = S.Q2;

%% ========================================================================
% 2. LOCK ALL PARAMETERS TO THE FINAL Q2 SPATIAL TEST
% =========================================================================
L        = double(Q2F.settings.L);
R0       = double(Q2F.settings.R0);
TEND_H   = double(Q2F.settings.Tend_h);
REC_DT_H = double(Q2F.settings.record_dt_h);
r_h      = double(Q2F.settings.r_h);
mu_h     = double(Q2F.settings.mu_h);
P_HIGH   = double(Q2F.settings.pHigh);

chiLow   = double(Q2F.hazard.chiLow);
chiHigh  = double(Q2F.hazard.chiHigh);
chiBar   = double(Q2F.hazard.chiBar);

N_SWAP_ATTEMPTS = double(Q2F.settings.nSwapAttempts);
N_REP = double(Q2F.settings.nRep);

assert(L==61,'Expected frozen Q2 domain L=61.');
assert(chiLow<chiHigh,'Expected chiLow < chiHigh.');
assert(strcmpi(Q2F.arrangementNames{2},'Dispersed'));
assert(strcmpi(Q2F.arrangementNames{3},'Random'));
assert(strcmpi(Q2F.arrangementNames{4},'Clustered'));

% These are the FINAL source-of-truth arrays that must be reproduced exactly.
sourceAUTC = double(Q2F.ensemble.AUTC_NV(:,2:4));
sourceMoran = double(Q2F.ensemble.initialMoran(:,2:4));

assert(size(sourceAUTC,1)==N_REP && size(sourceAUTC,2)==3);
assert(size(sourceMoran,1)==N_REP && size(sourceMoran,2)==3);

fprintf('\n============================================================\n');
fprintf('Q2 NEIGHBOURHOOD-ACCESS MECHANISM CONFIRMATION: FINAL\n');
fprintf('Replays the SAME independent FINAL Q2 seed families.\n');
fprintf('L=%d; R0=%g; Tend=%.1f h; record interval=%.2f h\n', ...
    L,R0,TEND_H,REC_DT_H);
fprintf('r=%.8f h^-1; mu=%.8f h^-1\n',r_h,mu_h);
fprintf('chi_low=%.4f; chi_high=%.4f; chi_bar=%.4f; p_high=%.3f\n', ...
    chiLow,chiHigh,chiBar,P_HIGH);
fprintf('Nrep=%d; matched-burden target NV=%d\n',N_REP,TARGET_NV);
fprintf('Spatial optimization attempts = %d (frozen from PILOT)\n',N_SWAP_ATTEMPTS);
fprintf('============================================================\n');

%% ========================================================================
% 3. PARALLEL
% =========================================================================
poolReady = false;
if USE_PARALLEL && license('test','Distrib_Computing_Toolbox')
    p = gcp('nocreate');
    if isempty(p) && AUTO_START_POOL
        try
            p = parpool('threads');
        catch ME
            warning('Could not start thread pool (%s). Running serially.',ME.message);
            p = [];
        end
    end
    poolReady = ~isempty(p);
end

%% ========================================================================
% 4. EXACT PILOT RERUN WITH EVENT LOGGING + EXTERNAL REPLAY
% =========================================================================
tmp = cell(N_REP,1);

if poolReady
    parfor rep=1:N_REP
        tmp{rep} = runMechanismRep( ...
            rep,L,R0,TEND_H,REC_DT_H,r_h,mu_h, ...
            chiLow,chiHigh,P_HIGH,N_SWAP_ATTEMPTS, ...
            TARGET_NV,SEED_PATTERN_BASE,SEED_SIM_BASE, ...
            sourceAUTC(rep,:),sourceMoran(rep,:));
    end
else
    for rep=1:N_REP
        tmp{rep} = runMechanismRep( ...
            rep,L,R0,TEND_H,REC_DT_H,r_h,mu_h, ...
            chiLow,chiHigh,P_HIGH,N_SWAP_ATTEMPTS, ...
            TARGET_NV,SEED_PATTERN_BASE,SEED_SIM_BASE, ...
            sourceAUTC(rep,:),sourceMoran(rep,:));
        fprintf('  completed replicate %d/%d\n',rep,N_REP);
    end
end

E = stackMechanism(tmp,nArr);

%% ========================================================================
% 5. HARD REPRODUCTION / REPLAY AUDITS
% =========================================================================
maxAUTCAbsDiff = max(abs(E.AUTC_NV - sourceAUTC),[],'all');
maxMoranAbsDiff = max(abs(E.initialMoran - sourceMoran),[],'all');

replayNVerr = max(E.maxReplayNVError,[],'all');
replayBirthErr = max(E.maxReplayBirthError,[],'all');
replayClassErr = max(E.maxReplayClassError,[],'all');

AUTC_PASS = maxAUTCAbsDiff <= 1e-9*max(1,max(abs(sourceAUTC),[],'all'));
MORAN_PASS = maxMoranAbsDiff <= 1e-10;
REPLAY_PASS = replayNVerr==0 && replayBirthErr==0 && replayClassErr==0;

fprintf('\n================ REPRODUCTION / REPLAY AUDIT ================\n');
fprintf('max |AUTC rerun - FINAL source| = %.3e : %s\n', ...
    maxAUTCAbsDiff,passFail(AUTC_PASS));
fprintf('max |Moran rerun - FINAL source| = %.3e : %s\n', ...
    maxMoranAbsDiff,passFail(MORAN_PASS));
fprintf('max replay NV count error          = %.0f : %s\n', ...
    replayNVerr,passFail(replayNVerr==0));
fprintf('max replay cumulative-birth error  = %.0f : %s\n', ...
    replayBirthErr,passFail(replayBirthErr==0));
fprintf('max replay low+high class error     = %.0f : %s\n', ...
    replayClassErr,passFail(replayClassErr==0));
fprintf('Overall replay validity             : %s\n', ...
    passFail(AUTC_PASS && MORAN_PASS && REPLAY_PASS));

assert(AUTC_PASS && MORAN_PASS && REPLAY_PASS, ...
    ['Mechanism audit failed exact reproduction/replay. Do not interpret ', ...
     'mechanistic quantities until this is resolved.']);

%% ========================================================================
% 6. PRIMARY MECHANISM SUMMARY
% =========================================================================
% Primary vacancy-access integral.
% FINAL uses the exact event-time integral accumulated during event-log
% replay, not a trapezoidal integral over the 1-h record grid.
AUE_LE = E.integratedLowEmptyEdgeHours;   % nRep x nArr

assert(isequal(size(AUE_LE),size(E.nLowInitial)), ...
    'Internal size mismatch: AUE_LE must be nRep x nArr.');
AUE_LE_perN0low = AUE_LE ./ E.nLowInitial;

% Low-lineage births.
% E.cumLowBirth(end,:,:) has size [1 x nRep x nArr].
LowBirthTotal = reshape(E.cumLowBirth(end,:,:), ...
    [size(E.cumLowBirth,2), size(E.cumLowBirth,3)]);      % nRep x nArr
assert(isequal(size(LowBirthTotal),size(E.nLowInitial)), ...
    'Internal size mismatch: LowBirthTotal must be nRep x nArr.');
LowBirthPerN0 = LowBirthTotal ./ E.nLowInitial;

% Total high-risk clearance events and their accessibility to low V.
HighClearN = E.highClearTotal;
HighClearAccessibleFrac = E.highClearAccessibleFrac;
HighClearMeanLowNbr = E.highClearMeanLowNbr;

% Matched-NV morphology.
MatchedCavity = E.matchedCavity;
MatchedTime = E.matchedTime_h;

% Time to low-lineage dominance.
TimeLow90 = E.timeLowFrac90_h;

% AUTC from exact SSA.
AUTC = E.AUTC_NV;

%% ========================================================================
% 7. PAIRED EFFECTS
% =========================================================================
% arrangement order: D=1 R=2 C=3
D=1; R=2; C=3;

Effects = struct();

Effects.AUE_CminusR = pairedMeanDiff( ...
    AUE_LE_perN0low(:,C),AUE_LE_perN0low(:,R),N_BOOT,SEED_BOOT+1);
Effects.AUE_DminusR = pairedMeanDiff( ...
    AUE_LE_perN0low(:,D),AUE_LE_perN0low(:,R),N_BOOT,SEED_BOOT+2);

Effects.Birth_CminusR = pairedMeanDiff( ...
    LowBirthPerN0(:,C),LowBirthPerN0(:,R),N_BOOT,SEED_BOOT+11);
Effects.Birth_DminusR = pairedMeanDiff( ...
    LowBirthPerN0(:,D),LowBirthPerN0(:,R),N_BOOT,SEED_BOOT+12);

Effects.AUTC_CminusR = pairedMeanDiff( ...
    AUTC(:,C),AUTC(:,R),N_BOOT,SEED_BOOT+21);
Effects.AUTC_DminusR = pairedMeanDiff( ...
    AUTC(:,D),AUTC(:,R),N_BOOT,SEED_BOOT+22);

Effects.HclearFrac_CminusR = pairedMeanDiff( ...
    HighClearAccessibleFrac(:,C),HighClearAccessibleFrac(:,R), ...
    N_BOOT,SEED_BOOT+31);
Effects.HclearFrac_DminusR = pairedMeanDiff( ...
    HighClearAccessibleFrac(:,D),HighClearAccessibleFrac(:,R), ...
    N_BOOT,SEED_BOOT+32);

Effects.HclearNbr_CminusR = pairedMeanDiff( ...
    HighClearMeanLowNbr(:,C),HighClearMeanLowNbr(:,R), ...
    N_BOOT,SEED_BOOT+41);
Effects.HclearNbr_DminusR = pairedMeanDiff( ...
    HighClearMeanLowNbr(:,D),HighClearMeanLowNbr(:,R), ...
    N_BOOT,SEED_BOOT+42);

Effects.Cavity_CminusR = pairedMeanDiffCompleteCases( ...
    MatchedCavity(:,C),MatchedCavity(:,R),N_BOOT,SEED_BOOT+51);
Effects.Cavity_DminusR = pairedMeanDiffCompleteCases( ...
    MatchedCavity(:,D),MatchedCavity(:,R),N_BOOT,SEED_BOOT+52);

%% ========================================================================
% 8. SUPPORTIVE ASSOCIATIONS
% =========================================================================
xAccess = AUE_LE_perN0low(:);
yAUTC = AUTC(:);

validAccess = isfinite(xAccess) & isfinite(yAUTC);
[rAccessAUTC,slopeAccessAUTC,intAccessAUTC] = ...
    simpleLinearAssociation(xAccess(validAccess),yAUTC(validAccess));

slopeAccessCI = bootstrapSlopeCI( ...
    xAccess(validAccess),yAUTC(validAccess),N_BOOT,SEED_BOOT+70);

xBirth = LowBirthPerN0(:);
validBirth = isfinite(xBirth) & isfinite(yAUTC);
[rBirthAUTC,slopeBirthAUTC,intBirthAUTC] = ...
    simpleLinearAssociation(xBirth(validBirth),yAUTC(validBirth));

slopeBirthCI = bootstrapSlopeCI( ...
    xBirth(validBirth),yAUTC(validBirth),N_BOOT,SEED_BOOT+71);

%% ========================================================================
% 9. MECHANISM DECISION
% =========================================================================
% The vacancy-access mechanism is considered supported at this pilot point
% if the already-observed clustered AUTC deficit is accompanied by:
%   (i) lower integrated low->empty access in C vs R, and
%   (ii) lower cumulative low-lineage births in C vs R,
% with both bootstrap 95% CIs entirely below zero.

supportAccess = Effects.AUE_CminusR.ci(2) < 0;
supportBirth  = Effects.Birth_CminusR.ci(2) < 0;
supportAUTC   = Effects.AUTC_CminusR.ci(2) < 0;

if supportAccess && supportBirth && supportAUTC
    mechanismDecision = 'FINAL_MECHANISM_CONFIRMED';
else
    mechanismDecision = 'FINAL_MECHANISM_NOT_CONFIRMED';
end

%% ========================================================================
% 10. CONSOLE RESULTS
% =========================================================================
fprintf('\n================ MECHANISM AUDIT SUMMARY =================\n');

for a=1:nArr
    fprintf(['%-10s | AUE_LE/NL0=%8.2f | low births/NL0=%6.3f | ', ...
        'high-clear accessible=%5.3f | mean low nbr/high-clear=%5.3f | ', ...
        'matched cavity=%6.4f | t_low90=%6.1f h\n'], ...
        arrNames{a}, ...
        mean(AUE_LE_perN0low(:,a),'omitnan'), ...
        mean(LowBirthPerN0(:,a),'omitnan'), ...
        mean(HighClearAccessibleFrac(:,a),'omitnan'), ...
        mean(HighClearMeanLowNbr(:,a),'omitnan'), ...
        mean(MatchedCavity(:,a),'omitnan'), ...
        mean(TimeLow90(:,a),'omitnan'));
end

fprintf('\nClustered - Random:\n');
printEffect('integrated low-empty access / NL0',Effects.AUE_CminusR);
printEffect('low-lineage births / NL0',Effects.Birth_CminusR);
printEffect('AUTC_NV',Effects.AUTC_CminusR);
printEffect('high-clear accessible fraction',Effects.HclearFrac_CminusR);
printEffect('low neighbours per high-clear',Effects.HclearNbr_CminusR);
printEffect(sprintf('cavity at first NV<=%d',TARGET_NV),Effects.Cavity_CminusR);

fprintf('\nDispersed - Random:\n');
printEffect('integrated low-empty access / NL0',Effects.AUE_DminusR);
printEffect('low-lineage births / NL0',Effects.Birth_DminusR);
printEffect('AUTC_NV',Effects.AUTC_DminusR);
printEffect('high-clear accessible fraction',Effects.HclearFrac_DminusR);
printEffect('low neighbours per high-clear',Effects.HclearNbr_DminusR);
printEffect(sprintf('cavity at first NV<=%d',TARGET_NV),Effects.Cavity_DminusR);

fprintf('\nSupportive associations across D/R/C realizations:\n');
fprintf('  accessible-edge hours -> AUTC: r=%+.3f, slope=%+.3f [%.3f, %.3f]\n', ...
    rAccessAUTC,slopeAccessAUTC,slopeAccessCI(1),slopeAccessCI(2));
fprintf('  low-lineage births    -> AUTC: r=%+.3f, slope=%+.3f [%.3f, %.3f]\n', ...
    rBirthAUTC,slopeBirthAUTC,slopeBirthCI(1),slopeBirthCI(2));

fprintf('\nFINAL mechanism decision: %s\n',mechanismDecision);

if strcmp(mechanismDecision,'FINAL_MECHANISM_CONFIRMED')
    fprintf(['Interpretation: the independent FINAL ensemble confirms the chain ', ...
        'clustered organization -> reduced survivor-vacancy access -> reduced ', ...
        'low-lineage birth output -> reduced viable tumour burden.\n']);
else
    fprintf(['Interpretation: the FINAL ensemble did not confirm the complete ', ...
        'vacancy-access mechanism chain. Do not freeze the Q2 mechanism.\n']);
end
fprintf('==========================================================\n');

%% ========================================================================
% 11. TABLES
% =========================================================================
Name = string(arrNames(:));

MeanAUE_LE_perN0low = mean(AUE_LE_perN0low,1,'omitnan').';
SEAUE_LE_perN0low = seColumns(AUE_LE_perN0low).';

MeanLowBirthPerN0 = mean(LowBirthPerN0,1,'omitnan').';
SELowBirthPerN0 = seColumns(LowBirthPerN0).';

MeanHighClearAccessibleFrac = mean(HighClearAccessibleFrac,1,'omitnan').';
SEHighClearAccessibleFrac = seColumns(HighClearAccessibleFrac).';

MeanHighClearLowNbr = mean(HighClearMeanLowNbr,1,'omitnan').';
SEHighClearLowNbr = seColumns(HighClearMeanLowNbr).';

MeanMatchedCavity = mean(MatchedCavity,1,'omitnan').';
SEMatchedCavity = seColumns(MatchedCavity).';

MeanMatchedTime_h = mean(MatchedTime,1,'omitnan').';
MeanTimeLow90_h = mean(TimeLow90,1,'omitnan').';

MeanAUTC_NV = mean(AUTC,1).';

Tsummary = table( ...
    Name,MeanAUE_LE_perN0low,SEAUE_LE_perN0low, ...
    MeanLowBirthPerN0,SELowBirthPerN0, ...
    MeanHighClearAccessibleFrac,SEHighClearAccessibleFrac, ...
    MeanHighClearLowNbr,SEHighClearLowNbr, ...
    MeanMatchedCavity,SEMatchedCavity, ...
    MeanMatchedTime_h,MeanTimeLow90_h,MeanAUTC_NV);

[Comparison,Metric,Effect,CI95_lo,CI95_hi] = effectsToColumns(Effects,TARGET_NV);
Tpaired = table(Comparison,Metric,Effect,CI95_lo,CI95_hi);

%% ========================================================================
% 12. SAVE MAT / CSV
% =========================================================================
outDir = fullfile(scriptDir, ...
    'Macro_Q2_NeighbourhoodAccess_Mechanism_FINAL_OUT');
if ~exist(outDir,'dir'), mkdir(outDir); end

outMAT = fullfile(outDir, ...
    'Macro_Q2_NeighbourhoodAccess_Mechanism_FINAL.mat');
outCSV = fullfile(outDir, ...
    'Macro_Q2_NeighbourhoodAccess_Mechanism_Summary.csv');
outPairCSV = fullfile(outDir, ...
    'Macro_Q2_NeighbourhoodAccess_Mechanism_PairedEffects.csv');
outPNG = fullfile(outDir, ...
    'Macro_Q2_NeighbourhoodAccess_Mechanism_FINAL.png');
outPDF = fullfile(outDir, ...
    'Macro_Q2_NeighbourhoodAccess_Mechanism_FINAL.pdf');

writetable(Tsummary,outCSV);
writetable(Tpaired,outPairCSV);

AUDIT = struct();
AUDIT.version = 'Q2_NEIGHBOURHOOD_ACCESS_MECHANISM_FINAL_v1';
AUDIT.runMode = 'final';
AUDIT.sourceFinalSpatial = finalFile;
AUDIT.settings = struct( ...
    'L',L,'R0',R0,'Tend_h',TEND_H,'recordDt_h',REC_DT_H, ...
    'r_h',r_h,'mu_h',mu_h,'chiLow',chiLow,'chiHigh',chiHigh, ...
    'chiBar',chiBar,'pHigh',P_HIGH,'nRep',N_REP, ...
    'nSwapAttempts',N_SWAP_ATTEMPTS,'targetNV',TARGET_NV, ...
    'seedPatternBase',SEED_PATTERN_BASE,'seedSimBase',SEED_SIM_BASE);

AUDIT.reproduction = struct( ...
    'maxAUTCAbsDiff',maxAUTCAbsDiff, ...
    'maxMoranAbsDiff',maxMoranAbsDiff, ...
    'maxReplayNVError',replayNVerr, ...
    'maxReplayBirthError',replayBirthErr, ...
    'maxReplayClassError',replayClassErr, ...
    'PASS',AUTC_PASS && MORAN_PASS && REPLAY_PASS);

AUDIT.arrangementNames = arrNames;
AUDIT.ensemble = E;
AUDIT.derived.AUE_LE = AUE_LE;
AUDIT.derived.AUE_LE_perN0low = AUE_LE_perN0low;
AUDIT.derived.LowBirthTotal = LowBirthTotal;
AUDIT.derived.LowBirthPerN0 = LowBirthPerN0;
AUDIT.effects = Effects;
AUDIT.association.accessAUTC = struct( ...
    'r',rAccessAUTC,'slope',slopeAccessAUTC,'intercept',intAccessAUTC, ...
    'slopeCI95',slopeAccessCI);
AUDIT.association.birthAUTC = struct( ...
    'r',rBirthAUTC,'slope',slopeBirthAUTC,'intercept',intBirthAUTC, ...
    'slopeCI95',slopeBirthCI);
AUDIT.mechanismDecision = mechanismDecision;
AUDIT.summary = Tsummary;
AUDIT.pairedEffects = Tpaired;

save(outMAT,'AUDIT','-v7.3');

%% ========================================================================
% 13. FIGURE
% =========================================================================
cDisp = hex2rgb('#6AA6A1');
cRand = hex2rgb('#D3A536');
cClust = hex2rgb('#B4534B');
cc = [cDisp;cRand;cClust];

fig = figure('Color','w','Position',[80 60 1380 820]);
tl = tiledlayout(fig,2,3,'TileSpacing','compact','Padding','compact');

% a. accessible empty neighbours per low viable cell
ax = nexttile(tl,1); hold(ax,'on');
for a=1:nArr
    plotMeanRibbon(ax,E.t_h,E.lowEmptyPerLow(:,:,a),cc(a,:),arrNames{a});
end
xlabel(ax,'Time (h)');
ylabel(ax,'Empty neighbours per low-\chi_F viable cell');
title(ax,'a  Low-lineage access to proliferative space');
legend(ax,'Location','best','Box','off','FontSize',7.5);
styleAxis(ax);

% b. cumulative low-lineage births per initial low cell
ax = nexttile(tl,2); hold(ax,'on');
for a=1:nArr
    Y = E.cumLowBirth(:,:,a) ./ E.nLowInitial(:,a).';
    plotMeanRibbon(ax,E.t_h,Y,cc(a,:),arrNames{a});
end
xlabel(ax,'Time (h)');
ylabel(ax,'Cumulative low-lineage births / N_{L,0}');
title(ax,'b  Expansion of the low-susceptibility lineage');
styleAxis(ax);

% c. low-lineage fraction among viable cells
ax = nexttile(tl,3); hold(ax,'on');
for a=1:nArr
    plotMeanRibbon(ax,E.t_h,E.lowFracViable(:,:,a),cc(a,:),arrNames{a});
end
xlabel(ax,'Time (h)');
ylabel(ax,'Low-lineage fraction among V cells');
ylim(ax,[0 1.03]);
title(ax,'c  Selective lineage enrichment');
styleAxis(ax);

% d. accessibility of high-risk clearances
ax = nexttile(tl,4); hold(ax,'on');
for a=1:nArr
    yy = HighClearAccessibleFrac(:,a);
