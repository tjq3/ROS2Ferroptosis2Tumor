function ExternalValidation_FSP1Consistency()
% =========================================================================
% ExternalValidation_FSP1Consistency
%
% Lightweight external consistency check for the multiscale
% Fenton -> LPO/ferroptosis -> tumour-growth framework.
%
% SCIENTIFIC AIM
% --------------
% Test only the pre-specified DIRECTIONAL cross-scale prediction already
% established in Fig.5 Q1:
%
%   higher ferroptotic commitment pressure  ->  lower viable tumour burden
%
% against independent FSP1 experimental data:
%
%   FSP1 loss -> higher tumour oxidized phospholipids (LPO)
%             -> lower orthotopic tumour expansion.
%
% IMPORTANT: THIS IS NOT A PARAMETER-FITTING OR FULL MODEL VALIDATION.
% -----------------------------------------------------------------------
% - No TD-CME / SD-RDME / mesoscopic parameter is re-fitted.
% - No experimental LPO value is converted into rho_L, lambda_F, or chi_F.
% - No tumour-growth curve is used to tune r, mu, lambda_F, M_L, or tau_L.
% - No new macro SSA simulation is performed.
% - The macro panel reads the already frozen Q1 output only.
%
% Therefore the result should be described as:
%   "external consistency with a key cross-scale prediction"
% and NOT as:
%   "experimental validation of the complete multiscale model".
%
% REQUIRED INPUTS
% ---------------
% 1) User-curated FSP1 tumour lipidomics:
%    LPO.xlsx (same folder as this script)
%       First sheet (typically Sheet1)
%
% 2) User-curated isogenic orthotopic tumour growth:
%    tumor.xlsx (same folder as this script)
%       First sheet (typically Sheet1)
%
% 3) Frozen macro-Q1 output generated by the existing Q1 calculation:
%    Macro_Q1_TargetedRefinement_FINAL_OUT/
%       Macro_Q1_TargetedRefinement_FINAL.mat
%    containing Q1R.
%
% PRIMARY EXTERNAL CONSISTENCY CRITERIA
% -------------------------------------
% 1) Experimental LPO shift:
%       Delta I_LPO = mean(I_LPO,KO)-mean(I_LPO,WT) > 0
% 2) Experimental tumour-growth shift:
%       R_AUTC = mean(AUTC_KO)/mean(AUTC_WT) < 1
% 3) Frozen model direction at reference chi_mu:
%       Spearman(chi_F, AUTC_NV/no-F) < 0
%
% Primary LPO index:
%   For each oxidized lipid species, z-score across all 10 tumours;
%   then average the species-wise z-scores within each tumour.
%   ALL quantified oxidized phospholipid species in the source sheet are
%   included a priori (no outcome-based feature selection).
%
% Sensitivity LPO index:
%   Repeat using only <oxo> or <COOH> species.
%
% OUTPUT
% ------
% Fig6_ExternalConsistency_FSP1_LIGHT_FINAL_OUT/
%   Fig6_ExternalConsistency_FSP1_LIGHT_FINAL.png
%   Fig6_ExternalConsistency_FSP1_LIGHT_FINAL.pdf
%   Fig6_ExternalConsistency_FSP1_LIGHT_FINAL.fig
%   Fig6_ExternalConsistency_FSP1_LIGHT_FINAL_data.mat
%   ExternalConsistency_summary.csv
%   ExternalConsistency_lipid_species.csv
%   ExternalConsistency_mouse_AUTC.csv
% =========================================================================

clc;
close all;

%% ========================================================================
% 0. SETTINGS
% =========================================================================
NBOOT = 50000;
SEED_BOOT = 960501;

% Journal-style colors. These are independent external-data colors and do
% not change any model conventions.
cWT = [0.38 0.38 0.38];
cKO = [0.73 0.23 0.20];
cModel = [0.12 0.47 0.71];

%% ========================================================================
% 1. LOCATE INPUT FILES (USER-CURATED VERSION)
% =========================================================================
scriptDir = fileparts(mfilename('fullpath'));
if isempty(scriptDir), scriptDir = pwd; end

% Accept the study copies or the original publisher workbooks.
lipidFile = findWorkbookByStem(scriptDir,'LPO');
growthFile = findWorkbookByStem(scriptDir,'tumor');
lipidSheet = '';
growthSheet = '';
if isempty(lipidFile)
    lipidFile = findWorkbookByStem(scriptDir,'41586_2025_9710_MOESM3_ESM');
    lipidSheet = 'Tumor Lipidomics Raw';
end
if isempty(growthFile)
    growthFile = findWorkbookByStem(scriptDir,'41586_2025_9710_MOESM14_ESM');
    growthSheet = '4f';
end

modelFile = findFirstExisting({ ...
    fullfile(fileparts(scriptDir),'CTMC','Macro_Q1_TargetedRefinement_FINAL_OUT', ...
        'Macro_Q1_TargetedRefinement_FINAL.mat'), ...
    fullfile(scriptDir,'Macro_Q1_TargetedRefinement_FINAL_OUT', ...
        'Macro_Q1_TargetedRefinement_FINAL.mat'), ...
    fullfile(scriptDir,'Macro_Q1_TargetedRefinement_FINAL.mat')});

assert(~isempty(lipidFile), [ ...
    'Cannot find the curated LPO workbook beside this script. ', ...
    'Expected LPO.xlsx or 41586_2025_9710_MOESM3_ESM.xlsx.']);
assert(~isempty(growthFile), [ ...
    'Cannot find the curated tumor workbook beside this script. ', ...
    'Expected tumor.xlsx or 41586_2025_9710_MOESM14_ESM.xlsx.']);
assert(~isempty(modelFile), [ ...
    'Cannot find Macro_Q1_TargetedRefinement_FINAL.mat in the ', ...
    'Macro_Q1_TargetedRefinement_FINAL_OUT folder.']);

fprintf('\n============================================================\n');
fprintf('LIGHTWEIGHT FSP1 EXTERNAL CONSISTENCY CHECK -- FIXED INPUT\n');
fprintf('Lipidomics : %s\n',lipidFile);
fprintf('Growth     : %s\n',growthFile);
fprintf('Frozen Q1  : %s\n',modelFile);
fprintf('NO downstream refitting; NO new macro SSA.\n');
fprintf('============================================================\n');

% Group identity is determined by column positions in the source sheets.
if isempty(lipidSheet)
    lipidSheet = firstSheetName(lipidFile);
end
if isempty(growthSheet)
    growthSheet = firstSheetName(growthFile);
end
fprintf('LPO sheet   : %s\n',lipidSheet);
fprintf('Tumor sheet : %s\n',growthSheet);

%% ========================================================================
% 2. READ FROZEN MODEL PREDICTION FROM FIG.5 Q1
% =========================================================================
S = load(modelFile,'Q1R');
assert(isfield(S,'Q1R'),'Frozen Q1 MAT does not contain Q1R.');
Q = S.Q1R;

assert(isfield(Q,'chiF') && isfield(Q,'chiMu') && ...
       isfield(Q,'AUTC_NV_norm') && isfield(Q,'referenceMu'), ...
    'Frozen Q1R lacks required fields.');

chiF = double(Q.chiF(:)).';
chiMu = double(Q.chiMu(:)).';
nChi = numel(chiF);
nMu = numel(chiMu);

AUTCmodel = orientStateMatrix(double(Q.AUTC_NV_norm),nMu,nChi,'AUTC_NV_norm');
iMuRef = round(double(Q.referenceMu.index));
assert(iMuRef>=1 && iMuRef<=nMu,'Invalid Q.referenceMu.index.');
chiMuRef = double(Q.referenceMu.chiMu);

modelY = AUTCmodel(iMuRef,:);
modelMask = isfinite(chiF) & isfinite(modelY);
modelRho = spearmanLocal(chiF(modelMask),modelY(modelMask));
modelDirectionPASS = isfinite(modelRho) && modelRho < 0 && ...
    modelY(find(modelMask,1,'last')) < modelY(find(modelMask,1,'first'));

%% ========================================================================
% 3. READ CURATED TUMOUR LIPIDOMICS (LPO.xlsx)
% =========================================================================
% Layout fixed from the user-curated workbook shown in the screenshot:
%   B4:B27   lipid-species names
%   C:G      Fsp1 WT, 5 tumours
%   H:L      FSP1 KO, 5 tumours
% Row 23 is blank in the curated sheet and is removed automatically.
% Header text is NOT used as a hard gate.

speciesRaw = readcell(lipidFile,'Sheet',lipidSheet,'Range','B4:B27');
WTraw = readmatrix(lipidFile,'Sheet',lipidSheet,'Range','C4:G27');
KOraw = readmatrix(lipidFile,'Sheet',lipidSheet,'Range','H4:L27');

species = string(speciesRaw(:));
WTraw = double(WTraw);
KOraw = double(KOraw);

assert(size(WTraw,2)==5, ...
    'LPO.xlsx: expected exactly 5 WT columns in C:G.');
assert(size(KOraw,2)==5, ...
    'LPO.xlsx: expected exactly 5 KO columns in H:L.');
assert(size(WTraw,1)==numel(species) && size(KOraw,1)==numel(species), ...
    'LPO.xlsx: species/data row counts do not match B4:B27, C4:G27, H4:L27.');

% Keep rows with a non-empty species label and complete numeric values.
% This drops the intentionally blank separator row but retains true zeros.
nonemptySpecies = ~ismissing(species) & strlength(strtrim(species))>0;
numericRows = all(isfinite(WTraw),2) & all(isfinite(KOraw),2);
keep = nonemptySpecies & numericRows;

species = species(keep);
X = [WTraw(keep,:) KOraw(keep,:)];

assert(size(X,2)==10,'LPO.xlsx: expected 10 tumour samples (5 WT + 5 KO).');
assert(size(X,1)>=10,'LPO.xlsx: too few quantified lipid species after cleaning.');

fprintf('Imported LPO data: %d lipid species, 5 WT tumours, 5 KO tumours.\n',size(X,1));

% Primary index: all quantified oxidized phospholipid species.
[scoreAll,Zall] = compositeSpeciesZScore(X);
scoreWT = scoreAll(1:5);
scoreKO = scoreAll(6:10);

lpoWTmean = mean(scoreWT);
lpoKOmean = mean(scoreKO);
lpoDelta = lpoKOmean-lpoWTmean;
pLPO = exactPermutationP(scoreWT,scoreKO);
[wtLPOmean,wtLPOCI] = bootMeanCI(scoreWT,NBOOT,SEED_BOOT+1);
[koLPOmean,koLPOCI] = bootMeanCI(scoreKO,NBOOT,SEED_BOOT+2);

% Sensitivity: oxo/COOH subset only, selected by chemical annotation and
% NOT by observed effect size.
maskOxo = contains(species,'<oxo>') | contains(species,'<COOH>');
if nnz(maskOxo)>=2
    [scoreCore,~] = compositeSpeciesZScore(X(maskOxo,:));
    coreWT = scoreCore(1:5);
    coreKO = scoreCore(6:10);
    lpoDeltaCore = mean(coreKO)-mean(coreWT);
    pLPOCore = exactPermutationP(coreWT,coreKO);
else
    % Sensitivity analysis is optional. Do not stop the primary validation
    % if user-curated lipid names no longer retain the <oxo>/<COOH> tags.
    warning(['Fewer than two <oxo>/<COOH>-annotated species were found. ', ...
        'Primary all-species LPO analysis will continue; sensitivity output ', ...
        'will be reported as NaN.']);
    scoreCore = nan(10,1);
    lpoDeltaCore = NaN;
    pLPOCore = NaN;
end

% Species-level summary for SI / audit. No pseudocount is introduced.
meanWTspecies = mean(X(:,1:5),2);
meanKOspecies = mean(X(:,6:10),2);
ratioSpecies = nan(size(meanWTspecies));
okRatio = meanWTspecies>0;
ratioSpecies(okRatio) = meanKOspecies(okRatio)./meanWTspecies(okRatio);
log2FCspecies = nan(size(meanWTspecies));
log2FCspecies(okRatio & meanKOspecies>0) = ...
    log2(meanKOspecies(okRatio & meanKOspecies>0) ./ ...
         meanWTspecies(okRatio & meanKOspecies>0));

%% ========================================================================
% 4. READ CURATED ORTHOTOPIC TUMOUR GROWTH (tumor.xlsx)
% =========================================================================
% Layout fixed from the user-curated workbook shown in the screenshot:
%   B4:B7   days post injection: 7, 11, 14, 18
%   C:I     Fsp1 WT, 7 mice
%   J:O     Fsp1 KO, 6 mice
% Each mouse trajectory is already normalized to its day-7 signal.

days = readmatrix(growthFile,'Sheet',growthSheet,'Range','B4:B7');
WTgrowth = readmatrix(growthFile,'Sheet',growthSheet,'Range','C4:I7');
KOgrowth = readmatrix(growthFile,'Sheet',growthSheet,'Range','J4:O7');

days = double(days(:));
WTgrowth = double(WTgrowth);
KOgrowth = double(KOgrowth);

validTime = isfinite(days);
days = days(validTime);
WTgrowth = WTgrowth(validTime,:);
KOgrowth = KOgrowth(validTime,:);

% Remove only fully empty columns defensively; true numeric zeros are kept.
WTgrowth = WTgrowth(:,any(isfinite(WTgrowth),1));
KOgrowth = KOgrowth(:,any(isfinite(KOgrowth),1));

assert(numel(days)==4, ...
    'tumor.xlsx: expected four time points in B4:B7.');
assert(size(WTgrowth,2)==7, ...
    'tumor.xlsx: expected 7 WT mice in C:I.');
assert(size(KOgrowth,2)==6, ...
    'tumor.xlsx: expected 6 KO mice in J:O.');
assert(all(isfinite(WTgrowth(:))) && all(isfinite(KOgrowth(:))), ...
    'tumor.xlsx: missing/non-numeric values found in selected growth blocks.');
assert(all(diff(days)>0), ...
    'tumor.xlsx: time points in B4:B7 must be strictly increasing.');

% Verify the published normalization visible in the curated workbook.
if max(abs(WTgrowth(1,:)-1))>1e-8 || max(abs(KOgrowth(1,:)-1))>1e-8
    warning(['First tumour-growth time point is not exactly 1 for all mice. ', ...
        'The analysis will continue, but please confirm the curated sheet.']);
end

fprintf('Imported tumour data: %d time points, %d WT mice, %d KO mice.\n', ...
    numel(days),size(WTgrowth,2),size(KOgrowth,2));

% Integrated expansion per mouse. Because all animals share the same time
% grid and are baseline-normalized, AUTC is a scale-free within-dataset
% summary; no mapping to N_V or to the model time axis is attempted.
AUTC_WT = trapz(days,WTgrowth,1).';
AUTC_KO = trapz(days,KOgrowth,1).';

meanAUTC_WT = mean(AUTC_WT);
meanAUTC_KO = mean(AUTC_KO);
R_AUTC = meanAUTC_KO/meanAUTC_WT;
[R_AUTC_check,R_AUTC_CI] = bootRatioOfMeans(AUTC_KO,AUTC_WT,NBOOT,SEED_BOOT+10);
assert(abs(R_AUTC_check-R_AUTC)<1e-12,'Bootstrap ratio helper returned an inconsistent point estimate.');
pAUTC = exactPermutationP(AUTC_WT,AUTC_KO);

% Curve summaries for plotting.
[meanWTcurve,loWTcurve,hiWTcurve] = bootCurveCI(WTgrowth,NBOOT,SEED_BOOT+20);
[meanKOcurve,loKOcurve,hiKOcurve] = bootCurveCI(KOgrowth,NBOOT,SEED_BOOT+30);

%% ========================================================================
% 5. PRE-SPECIFIED CONSISTENCY DECISION
% =========================================================================
lpoDirectionPASS = lpoDelta>0;
growthDirectionPASS = R_AUTC<1;
externalDirectionPASS = lpoDirectionPASS && growthDirectionPASS;
externalSignificancePASS = pLPO<0.05 && pAUTC<0.05;
overallPASS = modelDirectionPASS && externalDirectionPASS;

fprintf('\n================ PRIMARY RESULTS ================\n');
fprintf('Frozen model: Spearman rho(chi_F, AUTC_NV/no-F) = %.4f\n',modelRho);
fprintf('Model direction PASS: %s\n',passfail(modelDirectionPASS));
fprintf('\nExperimental tumour LPO (all %d quantified oxPL species):\n',numel(species));
fprintf('  WT composite mean = %+.4f\n',lpoWTmean);
fprintf('  KO composite mean = %+.4f\n',lpoKOmean);
fprintf('  Delta(KO-WT)       = %+.4f\n',lpoDelta);
fprintf('  exact two-sided permutation P = %.6f\n',pLPO);
fprintf('Sensitivity (<oxo>/<COOH>, n=%d): Delta=%+.4f, P=%.6f\n', ...
    nnz(maskOxo),lpoDeltaCore,pLPOCore);
fprintf('\nOrthotopic tumour expansion (tumor.xlsx):\n');
fprintf('  n WT/KO = %d/%d mice\n',numel(AUTC_WT),numel(AUTC_KO));
fprintf('  mean AUTC WT = %.4f\n',meanAUTC_WT);
fprintf('  mean AUTC KO = %.4f\n',meanAUTC_KO);
fprintf('  KO/WT AUTC ratio = %.4f [%.4f, %.4f]\n', ...
    R_AUTC,R_AUTC_CI(1),R_AUTC_CI(2));
fprintf('  exact two-sided permutation P = %.6f\n',pAUTC);
fprintf('\nDirectional external consistency: %s\n',passfail(externalDirectionPASS));
fprintf('Both external contrasts P<0.05 : %s\n',passfail(externalSignificancePASS));
fprintf('OVERALL key-rule consistency    : %s\n',passfail(overallPASS));
fprintf('=================================================\n');

%% ========================================================================
% 6. FIGURE: COMPACT 3-PANEL EXTERNAL CONSISTENCY CHECK
% =========================================================================
fig = figure('Color','w','Position',[80 120 1540 455]);
tl = tiledlayout(fig,1,3,'TileSpacing','compact','Padding','compact');

% -------------------------------------------------------------------------
% A. Locked model prediction (NO external fitting)
% -------------------------------------------------------------------------
ax1 = nexttile(tl,1); hold(ax1,'on');
plot(ax1,chiF,modelY,'-o','Color',cModel,'LineWidth',1.65, ...
    'MarkerFaceColor','w','MarkerSize',4.6);

% Reference line retained because y=1 is the normalized no-ferroptosis state.
% The label is placed inside the axes rather than attached to yline, avoiding
% clipping at the top boundary.
yline(ax1,1,':','Color',[0.68 0.68 0.68],'LineWidth',0.8, ...
    'HandleVisibility','off');
text(ax1,0.97,0.965,'No-ferroptosis baseline', ...
    'Units','normalized','HorizontalAlignment','right','VerticalAlignment','top', ...
    'FontSize',7.8,'Color',[0.42 0.42 0.42]);

xlabel(ax1,'Relative ferroptotic commitment, \chi_F = \lambda_F/r');
ylabel(ax1,'AUTC_{NV} / no-ferroptosis baseline');
title(ax1,'Pre-specified model prediction','FontWeight','normal', ...
    'HorizontalAlignment','left');
text(ax1,-0.105,1.045,'a','Units','normalized','FontWeight','bold', ...
    'FontSize',11,'Clipping','off');

% Compact provenance note; removes the previous incomplete "frozen Q1 at"
% annotation and avoids unnecessary parameter clutter in the main panel.
text(ax1,0.97,0.84,sprintf(['Frozen Q1; no external refitting\n', ...
    'Spearman \\rho = %.2f'],modelRho), ...
    'Units','normalized','HorizontalAlignment','right','VerticalAlignment','top', ...
    'FontSize',7.8,'Color',[0.30 0.30 0.30]);
styleAxis(ax1);

% -------------------------------------------------------------------------
% B. Independent tumour LPO shift
% -------------------------------------------------------------------------
ax2 = nexttile(tl,2); hold(ax2,'on');

% small deterministic horizontal jitter for individual tumours
jitWT = linspace(-0.055,0.055,numel(scoreWT));
jitKO = linspace(-0.055,0.055,numel(scoreKO));
scatter(ax2,1+jitWT,scoreWT,36,'o','filled', ...
    'MarkerFaceColor',cWT,'MarkerEdgeColor','w','LineWidth',0.4);
scatter(ax2,2+jitKO,scoreKO,36,'o','filled', ...
    'MarkerFaceColor',cKO,'MarkerEdgeColor','w','LineWidth',0.4);
errorbar(ax2,1,wtLPOmean,wtLPOmean-wtLPOCI(1),wtLPOCI(2)-wtLPOmean, ...
    's','Color',cWT,'MarkerFaceColor','w','LineWidth',1.3,'CapSize',6,'MarkerSize',7);
errorbar(ax2,2,koLPOmean,koLPOmean-koLPOCI(1),koLPOCI(2)-koLPOmean, ...
    's','Color',cKO,'MarkerFaceColor','w','LineWidth',1.3,'CapSize',6,'MarkerSize',7);
yline(ax2,0,':','Color',[0.72 0.72 0.72],'LineWidth',0.8, ...
    'HandleVisibility','off');
xlim(ax2,[0.55 2.45]);
xticks(ax2,[1 2]); xticklabels(ax2,{'Fsp1^{WT}','Fsp1^{KO}'});
ylabel(ax2,'Composite oxidized-phospholipid index (z score)');
title(ax2,'Independent tumour LPO shift','FontWeight','normal', ...
    'HorizontalAlignment','left');
text(ax2,-0.105,1.045,'b','Units','normalized','FontWeight','bold', ...
    'FontSize',11,'Clipping','off');

% Standard between-group comparison annotation.
yData = [scoreWT(:); scoreKO(:); wtLPOCI(:); koLPOCI(:)];
yMin2 = min(yData);
yMax2 = max(yData);
yRange2 = max(yMax2-yMin2,1);
yBracket = yMax2 + 0.10*yRange2;
yTick = 0.035*yRange2;
plot(ax2,[1 1 2 2],[yBracket-yTick yBracket yBracket yBracket-yTick], ...
    '-','Color',[0.25 0.25 0.25],'LineWidth',0.9,'HandleVisibility','off');
text(ax2,1.5,yBracket+0.035*yRange2, ...
    sprintf(['\\Delta I_{LPO} = +%.2f\n', ...
    'P_{perm} = %.4f'],lpoDelta,pLPO), ...
    'HorizontalAlignment','center','VerticalAlignment','bottom', ...
    'FontSize',7.9,'Color',[0.25 0.25 0.25],'Interpreter','tex');
ylim(ax2,[yMin2-0.12*yRange2, yBracket+0.22*yRange2]);
styleAxis(ax2);

% -------------------------------------------------------------------------
% C. Independent orthotopic tumour-growth consequence
% -------------------------------------------------------------------------
ax3 = nexttile(tl,3); hold(ax3,'on');
plotRibbon(ax3,days,meanWTcurve,loWTcurve,hiWTcurve,cWT,'Fsp1^{WT}');
plotRibbon(ax3,days,meanKOcurve,loKOcurve,hiKOcurve,cKO,'Fsp1^{KO}');
xlabel(ax3,'Days post injection');
ylabel(ax3,'Relative tumour bioluminescence (day 7 = 1)');
title(ax3,'Independent orthotopic tumour expansion','FontWeight','normal', ...
    'HorizontalAlignment','left');
text(ax3,-0.105,1.045,'c','Units','normalized','FontWeight','bold', ...
    'FontSize',11,'Clipping','off');

% Keep the legend away from the statistics block.
legend(ax3,'Location','northeast','Box','off','FontSize',8);

% Place the quantitative summary at the upper-left as requested.
text(ax3,0.04,0.95,sprintf(['AUTC_{KO}/AUTC_{WT} = %.2f\n', ...
    '95%% bootstrap CI = %.2f-%.2f\n', ...
    'P_{perm} = %.4f'], ...
    R_AUTC,R_AUTC_CI(1),R_AUTC_CI(2),pAUTC), ...
    'Units','normalized','HorizontalAlignment','left','VerticalAlignment','top', ...
    'FontSize',7.9,'Color',[0.26 0.26 0.26], ...
    'BackgroundColor','w','Margin',2);
styleAxis(ax3);

% Concise figure-level message. In a submitted journal figure this line can
% be removed entirely and left to the figure legend if desired.
sgtitle(tl, ...
    'External FSP1 tumour data support the predicted ferroptosis-growth relationship', ...
    'FontWeight','normal','FontSize',11.2);

%% ========================================================================
% 7. SAVE OUTPUTS
% =========================================================================
outDir = fullfile(scriptDir,'Fig6_ExternalConsistency_FSP1_LIGHT_FINAL_TOPJOURNAL_OUT');
if ~exist(outDir,'dir'), mkdir(outDir); end

base = fullfile(outDir,'Fig6_ExternalConsistency_FSP1_LIGHT_FINAL_TOPJOURNAL');
outPNG = [base '.png'];
outPDF = [base '.pdf'];
outFIG = [base '.fig'];
outMAT = [base '_data.mat'];
outSummaryCSV = fullfile(outDir,'ExternalConsistency_summary.csv');
outLipidCSV = fullfile(outDir,'ExternalConsistency_lipid_species.csv');
outMouseCSV = fullfile(outDir,'ExternalConsistency_mouse_AUTC.csv');

try
    axs=findall(fig,'Type','axes');
    for k=1:numel(axs), axtoolbar(axs(k),{}); end
catch
end

exportgraphics(fig,outPNG,'Resolution',600);
exportgraphics(fig,outPDF,'ContentType','vector');
savefig(fig,outFIG);

% Summary table.
Metric = string({ ...
    'model_spearman_chiF_vs_AUTCnorm'; ...
    'LPO_WT_mean_composite'; ...
    'LPO_KO_mean_composite'; ...
    'LPO_delta_KO_minus_WT'; ...
    'LPO_exact_permutation_P'; ...
    'LPO_core_oxoCOOH_delta'; ...
    'LPO_core_oxoCOOH_exact_P'; ...
    'tumour_AUTC_WT_mean'; ...
    'tumour_AUTC_KO_mean'; ...
    'tumour_AUTC_KO_over_WT'; ...
    'tumour_AUTC_ratio_CI_lo'; ...
    'tumour_AUTC_ratio_CI_hi'; ...
    'tumour_AUTC_exact_permutation_P'; ...
    'directional_external_consistency_PASS'; ...
    'overall_key_rule_consistency_PASS'});

Value = [ ...
    modelRho; ...
    lpoWTmean; ...
    lpoKOmean; ...
    lpoDelta; ...
    pLPO; ...
    lpoDeltaCore; ...
    pLPOCore; ...
    meanAUTC_WT; ...
    meanAUTC_KO; ...
    R_AUTC; ...
    R_AUTC_CI(1); ...
    R_AUTC_CI(2); ...
    pAUTC; ...
    double(externalDirectionPASS); ...
    double(overallPASS)];

Tsummary = table(Metric,Value);
writetable(Tsummary,outSummaryCSV);

% Species table.
Tlipid = table(species,meanWTspecies,meanKOspecies,ratioSpecies,log2FCspecies,maskOxo, ...
    'VariableNames',{'LipidSpecies','mean_WT','mean_KO','KO_over_WT', ...
    'log2FC_KO_vs_WT','isOxoOrCOOH'});
writetable(Tlipid,outLipidCSV);

% Mouse AUTC table.
Group = [repmat("Fsp1WT",numel(AUTC_WT),1); repmat("Fsp1KO",numel(AUTC_KO),1)];
Mouse = [(1:numel(AUTC_WT)).'; (1:numel(AUTC_KO)).'];
AUTC = [AUTC_WT; AUTC_KO];
Tmouse = table(Group,Mouse,AUTC);
writetable(Tmouse,outMouseCSV);

OUT = struct();
OUT.version = 'FSP1_LIGHT_EXTERNAL_CONSISTENCY_v4_TOPJOURNAL';
OUT.created = datestr(now,30);
OUT.note = ['Directional external consistency check only; no conversion of ', ...
    'experimental LPO into model parameters and no downstream refitting.'];
OUT.files.lipid = lipidFile;
OUT.files.lipidSheet = lipidSheet;
OUT.files.growth = growthFile;
OUT.files.growthSheet = growthSheet;
