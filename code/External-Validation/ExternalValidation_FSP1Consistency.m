function [score,Z] = compositeSpeciesZScore(X)
% X: species x samples.
mu=mean(X,2);
sd=std(X,0,2);
valid=isfinite(mu) & isfinite(sd) & sd>0;
assert(nnz(valid)>=2,'Too few non-degenerate lipid species.');
X=X(valid,:);
mu=mu(valid);
sd=sd(valid);
Z=(X-mu)./sd;
score=mean(Z,1).';
end

function p = exactPermutationP(x1,x2)
% Exact two-sided permutation test for difference in group means.
x1=double(x1(:)); x2=double(x2(:));
x1=x1(isfinite(x1)); x2=x2(isfinite(x2));
n1=numel(x1); n2=numel(x2); x=[x1;x2]; n=n1+n2;
assert(n1>=2 && n2>=2,'Need >=2 observations per group.');
obs=mean(x2)-mean(x1);
C=nchoosek(1:n,n1);
count=0;
for k=1:size(C,1)
    is1=false(n,1); is1(C(k,:))=true;
    d=mean(x(~is1))-mean(x(is1));
    if abs(d)>=abs(obs)-1e-12, count=count+1; end
end
p=count/size(C,1);
end

function [m,ci] = bootMeanCI(x,B,seed)
x=double(x(:)); x=x(isfinite(x));
m=mean(x);
rng(seed,'twister'); n=numel(x); b=zeros(B,1);
for k=1:B
    ii=randi(n,n,1);
    b(k)=mean(x(ii));
end
ci=[pctLocal(b,2.5) pctLocal(b,97.5)];
end

function [ratio,ci] = bootRatioOfMeans(num,den,B,seed)
num=double(num(:)); num=num(isfinite(num));
den=double(den(:)); den=den(isfinite(den));
ratio=mean(num)/mean(den);
rng(seed,'twister'); b=zeros(B,1);
for k=1:B
    in=randi(numel(num),numel(num),1);
    id=randi(numel(den),numel(den),1);
    b(k)=mean(num(in))/mean(den(id));
end
ci=[pctLocal(b,2.5) pctLocal(b,97.5)];
end

function [m,lo,hi] = bootCurveCI(Y,B,seed)
% Y: nTime x nMouse. Resample mice as whole trajectories, preserving
% within-mouse longitudinal dependence.
Y=double(Y);
nT=size(Y,1); n=size(Y,2);
m=mean(Y,2);
rng(seed,'twister');
b=zeros(nT,B);
for k=1:B
    ii=randi(n,n,1);
    b(:,k)=mean(Y(:,ii),2);
end
lo=zeros(nT,1); hi=zeros(nT,1);
for t=1:nT
    lo(t)=pctLocal(b(t,:),2.5);
    hi(t)=pctLocal(b(t,:),97.5);
end
end

function rho = spearmanLocal(x,y)
x=double(x(:)); y=double(y(:));
mask=isfinite(x)&isfinite(y); x=x(mask); y=y(mask);
rx=tiedRankLocal(x); ry=tiedRankLocal(y);
rx=rx-mean(rx); ry=ry-mean(ry);
den=sqrt(sum(rx.^2)*sum(ry.^2));
if den<=eps, rho=NaN; else, rho=sum(rx.*ry)/den; end
end

function r=tiedRankLocal(x)
x=double(x(:)); [sv,ord]=sort(x); r=zeros(size(x)); n=numel(x); i=1;
while i<=n
    j=i;
    while j<n && sv(j+1)==sv(i), j=j+1; end
    rr=(i+j)/2;
    r(ord(i:j))=rr;
    i=j+1;
end
end

function q = pctLocal(v,p)
v=sort(double(v(isfinite(v))));
if isempty(v), q=NaN; return; end
pos=1+(numel(v)-1)*p/100;
a=floor(pos); b=ceil(pos);
if a==b
    q=v(a);
else
    q=v(a)+(pos-a)*(v(b)-v(a));
end
end

