function f = findWorkbookByStem(baseDir,stem)
% Find an Excel workbook by exact stem, independent of hidden extension and
% with a case-insensitive fallback. Preference: xlsx > xlsm > xls.
f='';
exts={'.xlsx','.xlsm','.xls'};
for k=1:numel(exts)
    p=fullfile(baseDir,[stem exts{k}]);
    if isfile(p), f=p; return; end
end
% Case-insensitive fallback for Windows/macOS naming differences.
D=dir(baseDir);
for k=1:numel(D)
    if D(k).isdir, continue; end
    [~,nm,ext]=fileparts(D(k).name);
    if strcmpi(nm,stem) && any(strcmpi(ext,exts))
        f=fullfile(D(k).folder,D(k).name);
        return;
    end
end
end

